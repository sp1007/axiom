#!/usr/bin/env python3
"""T503 QA (round 0): callee-saved registers and stack alignment of Axiom code seen from an external C/asm caller.

  qa_abi_nonvolatile.py <compiler> <root> <tmp>

Gap closed: the engineer's oracle checks argument/return values only. The Windows x64 ABI also obliges an
Axiom *callee* (an `extern "C" fn` called from C) to preserve RBX, RSI, RDI, R12-R15 and XMM6-XMM15, and
every *caller* to hold RSP 16-byte aligned at a call (the shadow space is 32 bytes, stack arg 5 at [rsp+32]).
`nv_probe` (gcc-built naked asm in a `gcc -shared` DLL) loads sentinels into every non-volatile register,
calls an Axiom callback with 6 arguments (two on the stack) and reports every register that changed;
the callback keeps 10 doubles and 7 integers live across a C call (`nv_clobber`) that destroys every
volatile register, and `nv_clobber`/`nv_clobber5` report the RSP misalignment they observe at entry.
The expected callback result is computed here in Python; any mismatch is reported as FAIL with non-zero exit.
"""

import os
import shutil
import subprocess
import sys
import tempfile

DLL = "win64_nv_oracle"
M64 = (1 << 64) - 1
GPR = ["rbx", "rsi", "rdi", "r12", "r13", "r14", "r15"]


def gcc_path():
    gcc = shutil.which("gcc") or shutil.which("gcc", path="C:\\msys64\\ucrt64\\bin")
    if not gcc:
        print("gcc not found (it is the oracle of this test; ADR-0034 §7: no skip)")
        sys.exit(1)
    return gcc


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def expected_result():
    a = [1, 2, 3, 4, 5, 6]
    fs = 0.0
    for i in range(10):
        fs += (a[i % 6] * (0.5 + 0.25 * i)) * float(i + 1)
    isum = sum(a[j % 6] * (j + 3) + a[(j + 2) % 6] for j in range(7))
    return (int(fs) * 1000003 + isum * 7 + 0) & M64


def c_source(expected):
    asm = []
    asm.append("push %rbx\\n\\t push %rsi\\n\\t push %rdi\\n\\t push %r12\\n\\t push %r13\\n\\t push %r14\\n\\t push %r15")
    asm.append("sub $224, %rsp")
    asm.append("mov %rdx, 48(%rsp)")
    for i in range(6, 16):
        asm.append("movups %%xmm%d, %d(%%rsp)" % (i, 64 + 16 * (i - 6)))
    asm.append("mov %rcx, %r10")
    for k, r in enumerate(GPR):
        asm.append("movabs $0x%016X, %%%s" % (0x1111111111111111 * (k + 1), r))
    for i in range(6, 16):
        asm.append("movabs $0x%016X, %%rax" % (0x0101010101010101 * (0xA0 + i)))
        asm.append("movq %%rax, %%xmm%d" % i)
        asm.append("punpcklqdq %%xmm%d, %%xmm%d" % (i, i))
    asm.append("mov $1, %ecx\\n\\t mov $2, %edx\\n\\t mov $3, %r8d\\n\\t mov $4, %r9d")
    asm.append("movq $5, 32(%rsp)\\n\\t movq $6, 40(%rsp)")
    asm.append("call *%r10")
    asm.append("xor %r11d, %r11d")
    for k, r in enumerate(GPR):
        asm.append("movabs $0x%016X, %%rcx" % (0x1111111111111111 * (k + 1)))
        asm.append("cmp %%rcx, %%%s\\n\\t je 1f\\n\\t or $0x%x, %%r11\\n\\t 1:" % (r, 1 << k))
    for i in range(6, 16):
        asm.append("movabs $0x%016X, %%rcx" % (0x0101010101010101 * (0xA0 + i)))
        asm.append("movq %%xmm%d, %%rdx\\n\\t cmp %%rcx, %%rdx\\n\\t je 1f\\n\\t or $0x%x, %%r11\\n\\t 1:" %
                   (i, 1 << (7 + i - 6)))
        asm.append("movhlps %%xmm%d, %%xmm0\\n\\t movq %%xmm0, %%rdx\\n\\t cmp %%rcx, %%rdx\\n\\t je 1f\\n\\t "
                   "or $0x%x, %%r11\\n\\t 1:" % (i, 1 << (17 + i - 6)))
    asm.append("mov 48(%rsp), %rcx\\n\\t cmp %rcx, %rax\\n\\t je 1f\\n\\t or $0x40000000, %r11\\n\\t 1:")
    for i in range(6, 16):
        asm.append("movups %d(%%rsp), %%xmm%d" % (64 + 16 * (i - 6), i))
    asm.append("add $224, %rsp")
    asm.append("pop %r15\\n\\t pop %r14\\n\\t pop %r13\\n\\t pop %r12\\n\\t pop %rdi\\n\\t pop %rsi\\n\\t pop %rbx")
    asm.append("mov %r11, %rax\\n\\t ret")
    probe = "\n".join('        "%s\\n\\t"' % line for line in asm)

    return r'''/* generated by tests/ffi/win64_abi_oracle/qa_abi_nonvolatile.py (T503 QA) */
#include <stdint.h>
#define EXPORT __declspec(dllexport)
#define NAKED __attribute__((naked))

/* nv_probe(cb, expected): returns a bit mask of every non-volatile register the callback changed
   (bits 0-6 RBX,RSI,RDI,R12-R15; 7-16 XMM6-15 low half; 17-26 XMM6-15 high half) plus bit 30 if the
   callback result differs from `expected`. RSP is 16-byte aligned at the call. */
EXPORT NAKED uint64_t nv_probe(void *cb, uint64_t expected) {
    (void)cb; (void)expected;
    __asm__ volatile(
@@PROBE@@
    );
}

/* Destroys every volatile register; returns the RSP misalignment seen at entry (0 when the caller
   kept the stack 16-byte aligned at the call instruction). */
EXPORT NAKED uint64_t nv_clobber(void) {
    __asm__ volatile(
        "lea 8(%rsp), %rax\n\t and $15, %rax\n\t"
        "mov $-1, %rcx\n\t mov %rcx, %rdx\n\t mov %rcx, %r8\n\t mov %rcx, %r9\n\t"
        "mov %rcx, %r10\n\t mov %rcx, %r11\n\t"
        "pcmpeqd %xmm0, %xmm0\n\t movaps %xmm0, %xmm1\n\t movaps %xmm0, %xmm2\n\t"
        "movaps %xmm0, %xmm3\n\t movaps %xmm0, %xmm4\n\t movaps %xmm0, %xmm5\n\t"
        "ret\n\t"
    );
}

/* 5 integer arguments (the 5th on the stack at [rsp+40] at entry, above the 32-byte shadow space):
   returns misalignment | 0x100 if a != 11 ... | 0x1000 if e != 0x123456789. */
EXPORT NAKED uint64_t nv_clobber5(uint64_t a, uint64_t b, uint64_t c, uint64_t d, uint64_t e) {
    (void)a; (void)b; (void)c; (void)d; (void)e;
    __asm__ volatile(
        "lea 8(%rsp), %rax\n\t and $15, %rax\n\t"
        "cmp $11, %rcx\n\t je 1f\n\t or $0x100, %rax\n\t 1:\n\t"
        "cmp $22, %rdx\n\t je 1f\n\t or $0x200, %rax\n\t 1:\n\t"
        "cmp $33, %r8\n\t je 1f\n\t or $0x400, %rax\n\t 1:\n\t"
        "cmp $44, %r9\n\t je 1f\n\t or $0x800, %rax\n\t 1:\n\t"
        "movabs $0x123456789, %rcx\n\t cmp %rcx, 40(%rsp)\n\t je 1f\n\t or $0x1000, %rax\n\t 1:\n\t"
        "mov $-1, %rcx\n\t mov %rcx, %rdx\n\t mov %rcx, %r8\n\t mov %rcx, %r9\n\t"
        "mov %rcx, %r10\n\t mov %rcx, %r11\n\t"
        "pcmpeqd %xmm0, %xmm0\n\t movaps %xmm0, %xmm1\n\t movaps %xmm0, %xmm2\n\t"
        "movaps %xmm0, %xmm3\n\t movaps %xmm0, %xmm4\n\t movaps %xmm0, %xmm5\n\t"
        "ret\n\t"
    );
}

/* Positive control of the probe itself: a callee that violates the ABI (clobbers RBX and XMM7) must be
   reported as exactly bit 0 (RBX), bit 8 (XMM7 low) and bit 18 (XMM7 high). */
EXPORT NAKED uint64_t nv_evil(void) {
    __asm__ volatile("xor %eax, %eax\n\t xor %ebx, %ebx\n\t xorps %xmm7, %xmm7\n\t ret\n\t");
}
EXPORT uint64_t nv_probe_evil(void) { return nv_probe((void *)nv_evil, 0); }
'''.replace("@@PROBE@@", probe)


def ax_source(expected):
    o = []
    o.append("@link(\"%s\")" % DLL)
    o.append("extern \"C\" {")
    o.append("    fn nv_probe(cb: extern \"C\" fn(u64, u64, u64, u64, u64, u64) -> u64, expected: u64) -> u64;")
    o.append("    fn nv_clobber() -> u64;")
    o.append("    fn nv_probe_evil() -> u64;")
    o.append("    fn nv_clobber5(a: u64, b: u64, c: u64, d: u64, e: u64) -> u64;")
    o.append("}")
    o.append("")
    o.append("extern \"C\" fn nv_cb(a0: u64, a1: u64, a2: u64, a3: u64, a4: u64, a5: u64) -> u64 {")
    args = ["a0", "a1", "a2", "a3", "a4", "a5"]
    for i in range(10):
        o.append("    let f%d: f64 = (%s as f64) * %s;" % (i, args[i % 6], repr(0.5 + 0.25 * i)))
    for j in range(7):
        o.append("    let i%d: u64 = %s * %du64 + %s;" % (j, args[j % 6], j + 3, args[(j + 2) % 6]))
    o.append("    let k: u64 = unsafe { nv_clobber() };")
    terms = " + ".join("f%d * %s" % (i, repr(float(i + 1))) for i in range(10))
    o.append("    let fs: f64 = %s;" % terms)
    o.append("    let isum: u64 = %s;" % " + ".join("i%d" % j for j in range(7)))
    o.append("    return (fs as u64) * 1000003u64 + isum * 7u64 + k;")
    o.append("}")
    o.append("")
    o.append("fn deep(n: u64) -> u64 {")
    o.append("    let m: u64 = unsafe { nv_clobber() };")
    o.append("    if n == 0u64 { return m; }")
    o.append("    let r: u64 = deep(n - 1u64);")
    o.append("    return r + m + unsafe { nv_clobber() };")
    o.append("}")
    o.append("")
    o.append("fn main() -> i32 {")
    o.append("    let mut bad: i32 = 0;")
    o.append("    let mask: u64 = unsafe { nv_probe(nv_cb, 0x%XU64) };" % expected)
    o.append("    if mask != 0u64 { print(\"FAIL nv_probe mask=\"); print_int(mask as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    let again: u64 = unsafe { nv_probe(nv_cb, 0x%XU64) };" % expected)
    o.append("    if again != 0u64 { print(\"FAIL nv_probe(2) mask=\"); print_int(again as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    let ev: u64 = unsafe { nv_probe_evil() };")
    o.append("    if ev != 0x40101u64 { print(\"FAIL nv_probe_evil mask=\"); print_int(ev as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    let al: u64 = unsafe { nv_clobber() };")
    o.append("    if al != 0u64 { print(\"FAIL nv_clobber align=\"); print_int(al as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    let a5: u64 = unsafe { nv_clobber5(11u64, 22u64, 33u64, 44u64, 0x123456789u64) };")
    o.append("    if a5 != 0u64 { print(\"FAIL nv_clobber5 flags=\"); print_int(a5 as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    let dp: u64 = deep(5u64);")
    o.append("    if dp != 0u64 { print(\"FAIL deep align=\"); print_int(dp as i64); print(\"\\n\"); bad = bad + 1; }")
    o.append("    if bad != 0 { return bad; }")
    o.append("    print(\"WIN64-NV ok\\n\");")
    o.append("    return 0;")
    o.append("}")
    return "\n".join(o).replace("U64", "u64") + "\n"


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, **kw)


def text(b):
    return b.decode("utf-8", "replace").replace("\r\n", "\n")


def main():
    compiler, root, tmp = (os.path.abspath(x) for x in sys.argv[1:4])
    os.makedirs(tmp, exist_ok=True)
    gcc = gcc_path()
    work = tempfile.mkdtemp(prefix="w64nv_", dir=tmp)
    exp = expected_result()
    for sub, gopt, opt in (("o0", "-O0", "-O0"), ("o1", "-O2", "-O1")):
        d = os.path.join(work, sub)
        os.makedirs(d)
        write(os.path.join(d, DLL + ".c"), c_source(exp))
        r = run([gcc, gopt, "-shared", "-Wall", "-Werror", os.path.join(d, DLL + ".c"), "-o",
                 os.path.join(d, DLL + ".dll")])
        if r.returncode != 0:
            print("gcc failed: " + text(r.stderr)[:3000])
            return 1
        write(os.path.join(d, "nv.ax"), ax_source(exp))
        r = run([compiler, "build", opt, "--std-root", os.path.join(root, "std"), "-o", os.path.join(d, "nv.exe"),
                 os.path.join(d, "nv.ax")])
        if r.returncode != 0:
            print("axiom build %s failed: %s%s" % (opt, text(r.stdout)[:1500], text(r.stderr)[:3000]))
            return 1
        r = run([os.path.join(d, "nv.exe")], cwd=d, timeout=60)
        out = text(r.stdout)
        if r.returncode != 0 or out != "WIN64-NV ok\n":
            print("%s: rc=%d\n%s" % (opt, r.returncode, out[:3000]))
            return 1
    print("WIN64-NV-ORACLE PASS (callee-saved GPR/XMM6-15 sentinels, RSP alignment, 5th stack arg; x2 opt levels)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
