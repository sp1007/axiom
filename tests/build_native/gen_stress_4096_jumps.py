#!/usr/bin/env python3
"""Generator for tests/build_native/stress_4096_jumps.ax (T166).

Emits a single function `stress_jumps(x: i64) -> i64` with 1,600 grouped `if`
branches (> 3,500 machine basic blocks, > 4,800 JMP/JCC instructions, and
> 5,100 total branch fixups including overflow ASSERT fixups), well above
4,096 jumps in both -O0 and -O1.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_PATH = HERE / "stress_4096_jumps.ax"


def generate_source() -> str:
    n = 1600
    group = 100
    expected_sum = n * (n + 1) // 2  # 1280800
    lines = [
        "// test: run",
        "// timeout: 120",
        "// exit: 77",
        f"// stdout: {expected_sum}\\n",
        "// Generated by tests/build_native/gen_stress_4096_jumps.py (T166).",
        "",
        "fn stress_jumps(x: i64) -> i64 {",
        "    let mut r: i64 = 0;",
    ]
    for g in range(0, n, group):
        lines.append(f"    if x >= {g} {{")
        for k in range(g, g + group):
            if k % 8 == 0:
                lines.append(f"        if x == {k} {{ r = r + {k + 1}; }}")
            else:
                lines.append(f"        if x == {k} {{ r = {k + 1}; }}")
        lines.append("    }")
    lines += [
        "    r",
        "}",
        "",
        "fn main() -> i32 {",
        "    let mut sum: i64 = 0;",
        "    let mut i: i64 = 0;",
        f"    while i < {n} {{",
        "        sum = sum + stress_jumps(i);",
        "        i = i + 1;",
        "    }",
        "    print_int(sum);",
        '    print("\\n");',
        f"    if sum != {expected_sum} {{",
        "        return 1;",
        "    }",
        "    77",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    src = generate_source()
    if "--check" in sys.argv[1:]:
        if not OUT_PATH.is_file():
            print(f"missing {OUT_PATH}", file=sys.stderr)
            return 1
        actual = OUT_PATH.read_bytes().decode("utf-8", "replace")
        if actual != src:
            print(f"{OUT_PATH} is out of date", file=sys.stderr)
            return 1
        return 0
    OUT_PATH.write_text(src, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
