#!/usr/bin/env python3
"""T461a: large native programs must run.

Generates a deterministic program of <chunks> chunk functions with 100 calls each
(`pr(plain_f32(from_bits_f32(N)));`, `plain_f32(x) = x * 1.5 + 1.0`), builds it natively at -O0 and
-O1, runs it and compares stdout byte-for-byte with

  * a Python IEEE-754 binary32 reference (independent oracle, ADR-0034), and
  * `run --interp` (MIR interpreter), when `--interp` is given.

Every call in a chunk is a direct `call rel32` with a COFF relocation, so 330 chunks need ~66,000
relocations in one `.text` section: more than the 16-bit COFF NumberOfRelocations field holds.
Before T461a the object writer truncated the count (`rlen as u16`), the linker silently dropped the
excess relocations and the image crashed with 0xC0000005 on the first unpatched `call +0`. With
`--obj` the script also emits the `.obj` and checks the IMAGE_SCN_LNK_NRELOC_OVFL encoding (PE/COFF
spec: NumberOfRelocations = 0xFFFF, real entry count in the first relocation entry).

Usage (exec manifest): run_large.py <compiler> <root> <tmp> <chunks> [--interp] [--obj]
Prints `LARGE-PROGRAM PASS <chunks> <lines>` on success. Python stdlib only.
"""

import os
import random
import struct
import subprocess
import sys
import tempfile

CALLS_PER_CHUNK = 100
IMAGE_SCN_LNK_NRELOC_OVFL = 0x01000000


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def bits_f32(b):
    return struct.unpack("<f", struct.pack("<I", b))[0]


def generate(chunks):
    """Returns (source, expected stdout bytes)."""
    rng = random.Random(461)
    src = [
        "module large.program",
        "",
        "// Generated by tests/build_native/large_program/run_large.py (T461a). Do not edit.",
        "use std.core.float.to_bits_f32",
        "use std.core.float.from_bits_f32",
        "",
        "fn pr(x: f32) -> i32 {",
        "    print_int(to_bits_f32(x) as i64);",
        '    print("\\n");',
        "    0",
        "}",
        "",
        "fn plain_f32(x: f32) -> f32 {",
        "    x * 1.5 + 1.0",
        "}",
        "",
    ]
    want = []
    main = ["fn main() -> i32 {"]
    for c in range(chunks):
        src.append("fn chunk_%d() -> i32 {" % c)
        for _ in range(CALLS_PER_CHUNK):
            v = 0x3F800000 + rng.randint(0, 0x1000000)  # finite f32 in [1, 8)
            src.append("    pr(plain_f32(from_bits_f32(%du32)));" % v)
            # x * 1.5 and (..) + 1.0 are exact in binary64 for these operands, so one rounding
            # to binary32 per operation reproduces IEEE-754 binary32 arithmetic exactly.
            r = f32(f32(bits_f32(v) * 1.5) + 1.0)
            want.append("%d\n" % f32_bits(r))
        src.append("    0")
        src.append("}")
        main.append("    chunk_%d();" % c)
    main.append("    0")
    main.append("}")
    return "\n".join(src + main) + "\n", "".join(want).encode("ascii")


def diff_report(label, got, want):
    gl = got.decode("utf-8", "replace").split("\n")
    wl = want.decode("utf-8", "replace").split("\n")
    bad = [i for i in range(max(len(gl), len(wl))) if (gl[i] if i < len(gl) else None) != (wl[i] if i < len(wl) else None)]
    print("%s: %d line(s) got vs %d want, %d differing" % (label, len(gl) - 1, len(wl) - 1, len(bad)))
    for i in bad[:10]:
        print("  line %d: got %r want %r" % (i + 1, gl[i] if i < len(gl) else None, wl[i] if i < len(wl) else None))


def check_obj(path, chunks):
    """Validates relocation counts of the emitted COFF object (incl. NRELOC_OVFL)."""
    with open(path, "rb") as f:
        b = f.read()
    nsec = struct.unpack_from("<H", b, 2)[0]
    total = 0
    biggest = 0
    for s in range(nsec):
        h = 20 + 40 * s
        name = b[h:h + 8].rstrip(b"\0")
        ptr, = struct.unpack_from("<I", b, h + 24)
        n16, = struct.unpack_from("<H", b, h + 32)
        chars, = struct.unpack_from("<I", b, h + 36)
        if chars & IMAGE_SCN_LNK_NRELOC_OVFL:
            if n16 != 0xFFFF:
                print("obj: %s has NRELOC_OVFL but NumberOfRelocations=%d" % (name, n16))
                return False
            entries, sym, typ = struct.unpack_from("<IIH", b, ptr)
            if entries < 0x10000 or sym != 0 or typ != 0:
                print("obj: %s bad overflow entry count=%d sym=%d type=%d" % (name, entries, sym, typ))
                return False
            n = entries - 1
        else:
            n = n16
            if n == 0xFFFF:
                print("obj: %s NumberOfRelocations=0xFFFF without NRELOC_OVFL" % name)
                return False
        if ptr + 10 * (entries if chars & IMAGE_SCN_LNK_NRELOC_OVFL else n) > len(b):
            print("obj: %s relocation table past end of file" % name)
            return False
        total += n
        biggest = max(biggest, n)
    need = chunks * CALLS_PER_CHUNK * 2  # at least the two direct calls per statement
    if total < need:
        print("obj: only %d relocations, expected at least %d" % (total, need))
        return False
    if need >= 0xFFFF and biggest < 0xFFFF:
        print("obj: expected one section with >= 0xFFFF relocations (NRELOC_OVFL), largest has %d" % biggest)
        return False
    # Independent reader (ADR-0034): GNU objdump must see the same number of relocations.
    r = subprocess.run(["objdump", "-r", path], capture_output=True)
    if r.returncode != 0:
        print("objdump -r failed rc=%d: %s" % (r.returncode, r.stderr.decode("utf-8", "replace")[:500]))
        return False
    seen = sum(1 for ln in r.stdout.decode("utf-8", "replace").splitlines() if "IMAGE_REL_AMD64_" in ln or " R_X86_64_" in ln)
    if seen != total:
        print("obj: objdump -r lists %d relocations, header parse gives %d" % (seen, total))
        return False
    return True


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = [a for a in sys.argv[1:] if a.startswith("--")]
    if len(args) != 4:
        print("usage: run_large.py <compiler> <root> <tmp> <chunks> [--interp] [--obj]", file=sys.stderr)
        return 2
    compiler, root, tmp = (os.path.abspath(a) for a in args[:3])
    chunks = int(args[3])
    std_root = os.path.join(root, "std")
    os.makedirs(tmp, exist_ok=True)
    work = tempfile.mkdtemp(prefix="large_%d_" % chunks, dir=tmp)
    src, want = generate(chunks)
    src_path = os.path.join(work, "large_%d.ax" % chunks)
    with open(src_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)

    if "--interp" in flags:
        r = subprocess.run([compiler, "run", "--interp", "--std-root", std_root, src_path],
                           capture_output=True, timeout=3000)
        got = r.stdout.replace(b"\r\n", b"\n")
        if r.returncode != 0 or got != want:
            print("interp rc=%d %s" % (r.returncode, r.stderr.decode("utf-8", "replace")[:2000]))
            diff_report("interp", got, want)
            return 1

    for opt in ("-O0", "-O1"):
        exe = os.path.join(work, "large_%d%s.exe" % (chunks, opt))
        r = subprocess.run([compiler, "build", opt, "--std-root", std_root, src_path, "-o", exe],
                           capture_output=True, timeout=3000)
        if r.returncode != 0:
            print("build %s failed rc=%d: %s" % (opt, r.returncode, r.stderr.decode("utf-8", "replace")[:3000]))
            return 1
        r = subprocess.run([exe], capture_output=True, timeout=300)
        got = r.stdout.replace(b"\r\n", b"\n")
        if r.returncode != 0 or got != want:
            print("native %s rc=%d (0x%08X)" % (opt, r.returncode, r.returncode & 0xFFFFFFFF))
            diff_report("native " + opt, got, want)
            return 1

    if "--obj" in flags:
        obj = os.path.join(work, "large_%d.obj" % chunks)
        r = subprocess.run([compiler, "build", "--emit", "obj", "--std-root", std_root, src_path, "-o", obj],
                           capture_output=True, timeout=3000)
        if r.returncode != 0 or not os.path.exists(obj):
            print("obj build failed rc=%d: %s" % (r.returncode, r.stderr.decode("utf-8", "replace")[:3000]))
            return 1
        if not check_obj(obj, chunks):
            return 1

    print("LARGE-PROGRAM PASS %d %d" % (chunks, want.count(b"\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
