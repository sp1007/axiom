#!/usr/bin/env python3
"""Independent reference implementation of AXH64 v1 (bootstrap/axiom0/src/kernel/README.md).

Writes tests/unit/kernel/hash_vectors.txt, which the C unit test kernel_hash_vectors checks against
the kernel implementation; std/core/hash.ax (T069) checks the same file. Regenerating must give a
byte-identical file unless the algorithm changed (which needs an ADR).

    python tests/unit/kernel/gen_hash_vectors.py           # rewrite the file
    python tests/unit/kernel/gen_hash_vectors.py --check   # exit 1 if the file differs
"""
import os
import sys

MASK = (1 << 64) - 1
K1 = 0x9E3779B97F4A7C15
K2 = 0xC2B2AE3D27D4EB4F
K3 = 0x165667B19E3779F9
SEED = 0x27D4EB2F165667C5
M = 0x9FB21C651E98DF25


def rotl(x, n):
    n &= 63
    return ((x << n) | (x >> (64 - n))) & MASK if n else x


def rnd(h, w):
    m = (rotl((w * K2) & MASK, 31) * K1) & MASK
    return (rotl(h ^ m, 27) * K1 + K3) & MASK


def fold(h):
    return h ^ rotl(h, 15) ^ rotl(h, 40)


def axh64(data: bytes) -> int:
    h = SEED
    n = len(data)
    full = n - n % 8
    for i in range(0, full, 8):
        h = rnd(h, int.from_bytes(data[i:i + 8], "little"))
    if n % 8:
        h = rnd(h, int.from_bytes(data[full:], "little"))
    h ^= (n * K3) & MASK
    h = (fold(h) * M) & MASK
    h = (fold(h) * K2) & MASK
    return fold(h)


def seq(n):
    return bytes((i * 7 + 3) % 256 for i in range(n))


# (kind, data) in file order. kinds: hex, text, seq (see the file header).
TEXT = [
    "a", "ab", "abc", "abcd", "abcde", "abcdef", "abcdefg", "abcdefgh", "abcdefghi",
    "abcdefghijklmno", "abcdefghijklmnop", "abcdefghijklmnopq",
    "Xin chào thế giới", "fn", "let", "main", "std.core.hash", "fn main() -> i32 {",
    "The quick brown fox jumps over the lazy dog",
]
HEX = ["", "00", "ff", "61", "0000000000000000", "ffffffffffffffff", "000000000000000000",
       "0102030405060708", "e1babf", "f09f9880", "0700000000000000", "07000000"]
SEQ = [7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 100, 255, 256, 1000, 1024]

HEADER = """\
# AXH64 v1 reference vectors (bootstrap/axiom0/src/kernel/README.md, "Hash algorithm").
# Generated by tests/unit/kernel/gen_hash_vectors.py; checked by the unit test kernel_hash_vectors
# (axiom0) and by the std hash tests (T069). Do not edit by hand.
#
# Line format: <hash as 16 lowercase hex digits> <kind> <data>
#   hex   data = the key bytes in hex; "-" is the empty key
#   text  data = the key as UTF-8 text: everything after the single space following "text"
#   seq   data = decimal N; the key is N bytes with b[i] = (i * 7 + 3) mod 256
"""


def entries():
    out = []
    for h in HEX:
        out.append(("hex", h or "-", bytes.fromhex(h)))
    for t in TEXT:
        out.append(("text", t, t.encode("utf-8")))
    for n in SEQ:
        out.append(("seq", str(n), seq(n)))
    return out


def render():
    lines = [HEADER]
    for kind, shown, key in entries():
        lines.append("%016x %s %s\n" % (axh64(key), kind, shown))
    return "".join(lines)


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "hash_vectors.txt")
    text = render()
    if "--check" in sys.argv[1:]:
        with open(path, "r", encoding="utf-8", newline="") as f:
            ok = f.read() == text
        print("hash_vectors.txt " + ("up to date" if ok else "DIFFERS"))
        return 0 if ok else 1
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d vectors)" % (path, len(entries())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
