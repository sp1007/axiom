#!/usr/bin/env python3
"""T499: writes tests/run/numeric/tilde_tree/ctx_<C>.ax next to this script (ADR-0044 section 2).

Every expectation is computed with exact Python integers: `~x` of a leaf x: L inside a tree of context C is
`wrap_C(~x)` (the operand widened to C first), never `widen(wrap_L(~x))`.

usage: gen_tilde.py            rewrite the ctx_*.ax files
       gen_tilde.py --check    exit 1 if a checked-in file differs from what would be generated
"""
import os, sys

OUT = os.path.dirname(os.path.abspath(__file__))
CHECK = "--check" in sys.argv[1:]
BITS = {"u8": 8, "u16": 16, "u32": 32, "u64": 64, "usize": 64, "u128": 128,
        "i8": 8, "i16": 16, "i32": 32, "i64": 64, "isize": 64, "i128": 128}
def signed(t): return t.startswith("i")
def rng(t):
    b = BITS[t]
    return (-(1 << (b - 1)), (1 << (b - 1)) - 1) if signed(t) else (0, (1 << b) - 1)
def wrap(t, v):
    b = BITS[t]; v &= (1 << b) - 1
    if signed(t) and v >= 1 << (b - 1): v -= 1 << b
    return v
def fits(t, v):
    lo, hi = rng(t); return lo <= v <= hi
def can_widen(l, c):
    bl, bc = BITS[l], BITS[c]
    if signed(l) == signed(c): return bl < bc
    if not signed(l) and signed(c): return bl < bc
    return False
def lit(t, v):
    if v < 0:
        return "(%d%s)" % (v, t)
    return "%d%s" % (v, t)
def vals(t):
    lo, hi = rng(t)
    s = [0, 1, hi, (hi // 3) | 1]
    if signed(t): s += [-1, lo]
    return s

CTXS = ["i16", "i32", "i64", "i128", "isize", "usize"]
LEAVES = ["u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64"]
C_ADD = 1000
STALE = []

for c in CTXS:
    lines = ["// test: run", None,
             "// T499 (ADR-0044 section 2, SPEC-40 AXS-INT-052 rule 4): unary `~` of a narrow leaf inside a widening",
             "// tree of context %s is evaluated in %s (operand widened first). Expectations: exact Python integers." % (c, c),
             "// Each line: ok/BAD, then the result bits reinterpreted as i64.",
             "// GENERATED by tests/run/numeric/tilde_tree/gen_tilde.py (T499). Do not edit by hand.", ""]
    lines.append("fn report(ok: bool, bits: i64) {")
    lines.append("    if ok { print(\"ok \"); } else { print(\"BAD \"); }")
    lines.append("    print_int(bits);")
    lines.append("    print(\"\\n\");")
    lines.append("}")
    lines.append("")
    calls = []
    for l in LEAVES:
        if l == c or not can_widen(l, c):
            continue
        sc = signed(c)
        fa = "add_%s" % l
        if sc:
            lines.append("fn %s(x: %s, k: %s) -> %s {\n    let r: %s = ~x + k;\n    r\n}\n" % (fa, l, c, c, c))
        else:
            lines.append("fn %s(x: %s, k: %s) -> %s {\n    let r: %s = ~x - k;\n    r\n}\n" % (fa, l, c, c, c))
        fx = "xor_%s" % l
        lines.append("fn %s(x: %s, k: %s) -> %s {\n    let r: %s = k ^ ~x;\n    r\n}\n" % (fx, l, c, c, c))
        fn2 = "two_%s" % l
        if sc:
            lines.append("fn %s(x: %s, y: %s, k: %s) -> %s {\n    let r: %s = (~x + ~y) * k;\n    r\n}\n" % (fn2, l, l, c, c, c))
        else:
            lines.append("fn %s(x: %s, y: %s, k: %s) -> %s {\n    let r: %s = (~x & ~y) | k;\n    r\n}\n" % (fn2, l, l, c, c, c))
        for v in vals(l):
            nv = wrap(c, ~v)  # ~ in C of the widened operand
            if sc:
                e = nv + C_ADD
            else:
                e = nv - C_ADD
            assert fits(c, e), (l, c, v, e)
            calls.append((fa, "%s, %d%s" % (lit(l, v), C_ADD, c), e))
            k = 0x5A5A & ((1 << (BITS[c] - 1)) - 1)
            e2 = wrap(c, k ^ nv)
            calls.append((fx, "%s, %d%s" % (lit(l, v), k, c), e2))
            w = vals(l)[2]  # max
            nw = wrap(c, ~w)
            if sc:
                e3 = (nv + nw) * 3
                if not fits(c, e3):
                    continue
                calls.append((fn2, "%s, %s, 3%s" % (lit(l, v), lit(l, w), c), e3))
            else:
                e3 = wrap(c, (nv & nw) | 5)
                calls.append((fn2, "%s, %s, 5%s" % (lit(l, v), lit(l, w), c), e3))
    lines.append("fn main() -> i32 {")
    exp = []
    for (f, args, e) in calls:
        lines.append("    let v%d: %s = %s(%s);" % (len(exp), c, f, args))
        el = "(%d%s)" % (e, c) if e < 0 else "%d%s" % (e, c)
        lines.append("    report(v%d == %s, v%d as i64);" % (len(exp), el, len(exp)))
        exp.append("ok %d" % wrap("i64", e))
    lines.append("    print(\"OK tilde_tree %s\\n\");" % c)
    lines.append("    0")
    lines.append("}")
    exp.append("OK tilde_tree %s" % c)
    lines[1] = "// stdout: " + "\\n".join(exp) + "\\n"
    text = "\n".join(lines) + "\n"
    path = os.path.join(OUT, "ctx_%s.ax" % c)
    if CHECK:
        old = open(path, "rb").read().decode("utf-8") if os.path.isfile(path) else None
        if old != text:
            sys.stdout.buffer.write(("STALE %s\n" % os.path.basename(path)).encode())
            STALE.append(path)
    else:
        with open(path, "w", newline="\n") as f:
            f.write(text)

if CHECK:
    if STALE:
        sys.exit(1)
    sys.stdout.buffer.write(b"tilde_tree generated files current\n")
