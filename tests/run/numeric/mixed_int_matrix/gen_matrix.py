def all_files():
    f = {}
    for (t, _, _) in TYPES:
        f["pairs_%s.ax" % t] = gen_pairs(t)
    seed = 4550
    for ctx in CTX_LEAVES:
        seed += 1
        f["trees_%s.ax" % ctx] = gen_trees_file(ctx, seed)
    f["pattern_d.ax"] = gen_pattern_d()
    f["shift_counts.ax"] = gen_shift()
    for (a, c) in (("u8", "u8"), ("i32", "i64"), ("u64", "u128"), ("i128", "u8"), ("u32", "usize"), ("i16", "i128")):
        f["shift_trap_hi_%s_%s.ax" % (a, c)] = gen_shift_trap(a, c, bits(a), "hi")
    f["shift_trap_neg_i32_i8.ax"] = gen_shift_trap("i32", "i8", -1, "neg")
    f["shift_trap_neg_u64_i64.ax"] = gen_shift_trap("u64", "i64", -1, "neg")
    f["shift_trap_neg_i128_i128.ax"] = gen_shift_trap("i128", "i128", -1, "neg")
    f["shift_trap_big_u32_i64.ax"] = gen_shift_trap("u32", "i64", (1 << 32) + 5, "big")
    f["shift_trap_big_u8_u64.ax"] = gen_shift_trap("u8", "u64", (1 << 32) + 3, "big")
    f["index_types.ax"] = gen_index()
    f["index_trap_i64_alias.ax"] = gen_index_trap("i64", (1 << 32) + 1, "alias")
    f["index_trap_u64_alias.ax"] = gen_index_trap("u64", (1 << 32) + 2, "alias")
    f["index_trap_i32_neg.ax"] = gen_index_trap("i32", -1, "negative")
    f["index_trap_i8_neg.ax"] = gen_index_trap("i8", -128, "negative")
    f["index_trap_u8_oob.ax"] = gen_index_trap("u8", 255, "past the end")
    f["index_trap_i128_neg.ax"] = gen_index_trap("i128", -1, "negative")
