def gen_index():
    p = Program("index_types")
    arr = [10, 20, 30, 40, 50, 60, 70, 80]
    p.decl("fn at_arr(a: view<[8]i32>, i: usize) -> i32 { (*a)[i] }\n")
    for (t, _, _) in TYPES:
        p.decl("fn idx_%s(a: view<[8]i32>, i: %s) -> i32 { (*a)[i] }\n" % (t, t))
        p.decl("fn idx1_%s(a: view<[8]i32>, i: %s) -> i32 { (*a)[i + 1] }\n" % (t, t))
        p.decl("fn idxm_%s(a: view<[8]i32>, i: %s) -> i32 { (*a)[i - 1] }\n" % (t, t))
        for k in (0, 3, 6):
            p.bad("idx_%s(view(ARR), %s) != %d" % (t, lit(k, t), arr[k]))
        for k in (0, 3, 6):
            p.bad("idx1_%s(view(ARR), %s) != %d" % (t, lit(k, t), arr[k + 1]))
        for k in (1, 4, 7):
            p.bad("idxm_%s(view(ARR), %s) != %d" % (t, lit(k, t), arr[k - 1]))
    # composite mixed-width index expressions: (i + off) with different types
    combos = [("i8", "u16"), ("u8", "i64"), ("i32", "i16"), ("u32", "u8"), ("isize", "i8"), ("i16", "u8"), ("u64", "u16"),
              ("usize", "u8"), ("i128", "u8"), ("u128", "u32"), ("u16", "i8")]
    for (i, o) in combos:
        j = join(i, o)
        assert j is not None, (i, o)
        p.decl("fn mix_%s_%s(a: view<[8]i32>, i: %s, o: %s) -> i32 { (*a)[i + o] }\n" % (i, o, i, o))
        p.decl("fn mixd_%s_%s(a: view<[8]i32>, i: %s, o: %s) -> i32 { (*a)[(i + o * 2) - 1] }\n" % (i, o, i, o))
        for (vi, vo) in ((1, 2), (0, 7), (3, 3), (5, 0)):
            p.bad("mix_%s_%s(view(ARR), %s, %s) != %d" % (i, o, lit(vi, i), lit(vo, o), arr[vi + vo]))
        for (vi, vo) in ((2, 1), (1, 3), (4, 1)):
            p.bad("mixd_%s_%s(view(ARR), %s, %s) != %d" % (i, o, lit(vi, i), lit(vo, o), arr[vi + vo * 2 - 1]))
    # slice indexing: base is a slice view of the array, index of a non-usize type
    text = p.render().replace("ARR", "arr")
    # `arr` must exist in every chunk
    text = text.replace("() -> i32 {\n    if", "() -> i32 {\n    let arr: [8]i32 = [10, 20, 30, 40, 50, 60, 70, 80];\n    if")
    return text


def gen_index_trap(t, v, what, xfail=None):
    # xfail: id of the fix task (ADR-0044 section 1); the fix task removes the directive.
    head = ["// test: run", "// exit: 101", "// stdout: before\\n", "// stderr-contains: index out of bounds"]
    if xfail:
        head.append("// xfail: %s 128-bit index is truncated to usize before the bounds check (ADR-0044 section 1)" % xfail)
    return "\n".join(head + [GEN,
        "// %s: index of type %s = %s must trap (a truncating cast to a narrower type would alias a valid element)." % (what, t, v),
        "",
        "fn at(a: view<[8]i32>, i: %s) -> i32 { (*a)[i] }" % t,
        "",
        "fn main() -> i32 {",
        "    print(\"before\\n\");",
        "    let a: [8]i32 = [10, 20, 30, 40, 50, 60, 70, 80];",
        "    let r: i32 = at(view(a), %s);" % lit(v, t),
        "    print_int(r as i64);",
        "    print(\"\\nUNREACHABLE\\n\");",
        "    0",
        "}", ""])


