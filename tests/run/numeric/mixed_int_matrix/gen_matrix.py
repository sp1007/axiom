def gen_promoted_trap(name, sig, body, args, ctx, msg, what):
    return "\n".join([
        "// test: run", "// exit: 101", "// stdout: before\\n", "// stderr-contains: %s" % msg, GEN,
        "// %s" % what, "",
        "fn calc(%s) -> %s {" % (sig, ctx),
        "    let r: %s = %s;" % (ctx, body),
        "    r",
        "}", "",
        "fn main() -> i32 {",
        "    print(\"before\\n\");",
        "    let r: %s = calc(%s);" % (ctx, args),
        "    print_int(r as i64);",
        "    print(\"\\nUNREACHABLE\\n\");",
        "    0",
        "}", ""])


def gen_no_trap_in_ctx():
    """Intermediates that would overflow the narrow operand type are fine in the promoted context."""
    p = Program("promoted_no_trap")
    p.decl("fn a1(b: u8) -> i64 { let r: i64 = b * 2 + 0; r }")
    p.decl("fn a2(b: u8, c: u8) -> i32 { let r: i32 = b * c; r }")
    p.decl("fn a3(s: i8) -> i16 { let r: i16 = s * s; r }")
    p.decl("fn a4(s: i8, w: i16) -> i16 { let r: i16 = (w + 4) - s; r }")
    p.decl("fn a5(s: i8, w: i64) -> i64 { let r: i64 = (s / (s + 127)) + w; r }")
    p.decl("fn a6(s: i8, w: i64) -> i64 { let r: i64 = (-s) + w; r }")
    p.decl("fn a7(b: u8, w: u128) -> u128 { let r: u128 = (b * b * b * b * b * b * b * b) + w; r }")
    p.decl("fn a8(h: u16, w: i32) -> i32 { let r: i32 = (h * h) - w; r }")
    p.bad("a1(%s) != %s" % (lit(255, "u8"), lit(510, "i64")))
    p.bad("a2(%s, %s) != %s" % (lit(255, "u8"), lit(255, "u8"), lit(65025, "i32")))
    p.bad("a3(%s) != %s" % (lit(-128, "i8"), lit(16384, "i16")))
    p.bad("a4(%s, %s) != %s" % (lit(-128, "i8"), lit(32000, "i16"), lit(32000 + 4 + 128, "i16")))
    p.bad("a5(%s, %s) != %s" % (lit(-128, "i8"), lit(1000, "i64"), lit(1128, "i64")))
    p.bad("a6(%s, %s) != %s" % (lit(-128, "i8"), lit(1000, "i64"), lit(1128, "i64")))
    p.bad("a7(%s, %s) != %s" % (lit(255, "u8"), lit(1, "u128"), lit(255 ** 8 + 1, "u128")))
    p.bad("a8(%s, %s) != %s" % (lit(65535, "u16"), lit(-1, "i32"), lit(65535 * 65535 + 1, "i32")) if 65535 * 65535 + 1 <= hi("i32") else "false")
    return p.render()


