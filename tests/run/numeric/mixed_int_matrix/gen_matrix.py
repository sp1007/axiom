def gen_pattern_d():
    # task values and the SPEC-40 AXS-INT-052 values
    def total(s64, s32, u16v, b8, s8):
        a = s64 + s32 * 3
        n = u16v + b8 * 2 + s8 - 7
        d = 4 - s8
        return a - trunc_div(n, d)

    t1 = total(5000000000, -100000, 3000, 200, -50)
    t2 = total(100000, -2000, 500, 200, -50)
    assert t1 == 4999699939 and t2 == 93985
    # the same shape in i128 with u64/u32/i32 leaves
    def total128(s128, s64, u64v, u32v, s32):
        a = s128 + s64 * 3
        n = u64v + u32v * 2 + s32 - 7
        d = 4 - s32
        return a - trunc_div(n, d)
    t3 = total128(5000000, 100000, 900000, 40000, -2000)
    big = total128(170141183460469231731687303715884105000, -1000, 18446744073709551615, 4294967295, -2147483648)
    # (mask >> sh) & 0x3F  chain of REQ-OWNER-007's second example, in i64
    mask, sh, delta, step, scale = 0xFFFF, 3, -7, 5, 1000
    shift_tree = (((mask >> sh) & 0x3F) + delta * step - 5) * scale
    shift_tree = trunc_div(shift_tree, (1 << sh) + 3)
    assert shift_tree == 2090
    out = ["// test: run",
           "// stdout: %d\\n%d\\n%d\\nOK pattern_d\\n" % (t1, t2, shift_tree),
           GEN, "",
           "// REQ-OWNER-007 Pattern D with the task values: b8 = 200u8, s8 = -50i8, u16v = 3000u16, s32 = -100000i32,",
           "// s64 = 5000000000i64.  Without promotion `b8 * 2` would overflow u8 and `4 - s8` would be an i8 expression.",
           "fn pattern_d(s64: i64, s32: i32, u16v: u16, b8: u8, s8: i8) -> i64 {",
           "    let total: i64 = (s64 + s32 * 3) - (u16v + b8 * 2 + s8 - 7) / (4 - s8);",
           "    total",
           "}", "",
           "fn shift_tree(mask: u32, sh: u8, delta: i16, step: i32, scale: i64) -> i64 {",
           "    let r: i64 = (((mask >> sh) & 0x3F) + delta * step - 5) * scale / ((1 << sh) + 3);",
           "    r",
           "}", "",
           "fn pattern_d_128(s128: i128, s64: i64, u64v: u64, u32v: u32, s32: i32) -> i128 {",
           "    let total: i128 = (s128 + s64 * 3) - (u64v + u32v * 2 + s32 - 7) / (4 - s32);",
           "    total",
           "}", "",
           "fn main() -> i32 {",
           "    let b8: u8 = 200;",
           "    let s8: i8 = -50;",
           "    let u16v: u16 = 3000;",
           "    let s32: i32 = -100000;",
           "    let s64: i64 = 5000000000;",
           "    let total: i64 = (s64 + s32 * 3) - (u16v + b8 * 2 + s8 - 7) / (4 - s8);",
           "    print_int(total);",
           "    print(\"\\n\");",
           "    print_int(pattern_d(100000i64, -2000i32, 500u16, 200u8, -50i8));",
           "    print(\"\\n\");",
           "    print_int(shift_tree(65535u32, 3u8, -7i16, 5i32, 1000i64));",
           "    print(\"\\n\");",
           "    if pattern_d(5000000000i64, -100000i32, 3000u16, 200u8, -50i8) != %s { return 1; }" % lit(t1, "i64"),
           "    if pattern_d(%s, %s, 65535u16, 255u8, %s) != %s { return 2; }" % (
               lit(0, "i64"), lit(-2147483648, "i32"), lit(-128, "i8"),
               lit(total(0, -2147483648, 65535, 255, -128), "i64")),
           "    if pattern_d(%s, %s, 0u16, 0u8, 127i8) != %s { return 3; }" % (
               lit(9223372036854775807 - 6 * 10 ** 8, "i64"), lit(-2147483648, "i32"),
               lit(total(9223372036854775807 - 6 * 10 ** 8, -2147483648, 0, 0, 127), "i64")),
           "    if pattern_d_128(5000000i128, 100000i64, 900000u64, 40000u32, -2000i32) != %s { return 4; }" % lit(t3, "i128"),
           "    if pattern_d_128(%s, %s, 18446744073709551615u64, 4294967295u32, %s) != %s { return 5; }" % (
               lit(170141183460469231731687303715884105000, "i128"), lit(-1000, "i64"), lit(-2147483648, "i32"),
               lit(big, "i128")),
           "    print(\"OK pattern_d\\n\");",
           "    0",
           "}"]
    return "\n".join(out) + "\n"


