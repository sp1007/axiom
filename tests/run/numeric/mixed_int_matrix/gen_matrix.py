    f["index_trap_u128_alias.ax"] = gen_index_trap("u128", (1 << 64) + 1, "alias", "T496")
    f["index_trap_u128_alias_hi.ax"] = gen_index_trap("u128", (1 << 127) + 2, "alias", "T496")
    f["index_trap_i128_alias.ax"] = gen_index_trap("i128", -(1 << 64) + 1, "alias", "T496")
