# Pair matrix: every valid (A, B) pair, arithmetic / bitwise / comparison on boundary values
# ---------------------------------------------------------------------------------------------------------------
ARITH = [("add", "+", lambda x, y: x + y), ("sub", "-", lambda x, y: x - y), ("mul", "*", lambda x, y: x * y)]
BITOPS = [("and", "&", lambda x, y: x & y), ("or", "|", lambda x, y: x | y), ("xor", "^", lambda x, y: x ^ y)]
CMPS = [("<", lambda x, y: x < y), ("<=", lambda x, y: x <= y), (">", lambda x, y: x > y),
        (">=", lambda x, y: x >= y), ("==", lambda x, y: x == y), ("!=", lambda x, y: x != y)]


def gen_pairs(a):
    p = Program("pairs_%s" % a)
    for (b, _, _) in TYPES:
        j = join(a, b)
        if j is None:
            continue
        sfx = "%s_%s" % (a, b)
        # declared-context helpers + inferred-type check (`let r = a op b; let back: J = r` fails to type if r is not J)
        for (opn, sym, f) in ARITH + BITOPS:
            p.decl("fn %s_%s(a: %s, b: %s, e: %s) -> i32 {\n    let r: %s = a %s b;\n    if r != e { return 1; }\n"
                   "    let q = a %s b;\n    let back: %s = q;\n    if back != e { return 2; }\n    0\n}\n" % (
                       opn, sfx, a, b, j, j, sym, sym, j))
        for (opn, sym) in (("div", "/"), ("rem", "%")):
            p.decl("fn %s_%s(a: %s, b: %s, e: %s) -> i32 {\n    let r: %s = a %s b;\n    if r != e { return 1; }\n"
                   "    let q = a %s b;\n    let back: %s = q;\n    if back != e { return 2; }\n    0\n}\n" % (
                       opn, sfx, a, b, j, j, sym, sym, j))
        p.decl("fn cmp_%s(a: %s, b: %s) -> i32 {\n    let mut m: i32 = 0;\n" % (sfx, a, b) +
               "".join("    if a %s b { m = m | %d; }\n" % (sym, 1 << k) for k, (sym, _) in enumerate(CMPS)) +
               "    m\n}\n")
        for va in values(a):
            for vb in values(b):
                for (opn, sym, f) in ARITH + BITOPS:
                    r = f(va, vb)
                    if lo(j) <= r <= hi(j):
                        p.bad("%s_%s(%s, %s, %s) != 0" % (opn, sfx, lit(va, a), lit(vb, b), lit(r, j)))
                if vb != 0:
                    q = trunc_div(va, vb)
                    if lo(j) <= q <= hi(j):
                        p.bad("div_%s(%s, %s, %s) != 0" % (sfx, lit(va, a), lit(vb, b), lit(q, j)))
                        p.bad("rem_%s(%s, %s, %s) != 0" % (sfx, lit(va, a), lit(vb, b), lit(va - q * vb, j)))
                mask = sum((1 << k) for k, (sym, f) in enumerate(CMPS) if f(va, vb))
                p.bad("cmp_%s(%s, %s) != %d" % (sfx, lit(va, a), lit(vb, b), mask))
    return p.render()


# ---------------------------------------------------------------------------------------------------------------
# Random arithmetic trees per context type (Pattern D shape)
# ---------------------------------------------------------------------------------------------------------------
CTX_LEAVES = {
    "i16": ["i8", "i16", "u8"],
    "i32": ["i8", "i16", "i32", "u8", "u16"],
    "i64": ["i8", "i16", "i32", "i64", "u8", "u16", "u32"],
    "i128": ["i8", "i16", "i32", "i64", "i128", "u8", "u16", "u32", "u64", "usize", "isize"],
    "isize": ["i8", "i16", "i32", "u8", "u16", "u32"],
    "u16": ["u8", "u16"],
    "u32": ["u8", "u16", "u32"],
    "u64": ["u8", "u16", "u32", "u64"],
    "u128": ["u8", "u16", "u32", "u64", "u128", "usize"],
    "usize": ["u8", "u16", "u32", "usize"],
}


class Reject(Exception):
    pass


class Node:
    pass


class Var(Node):
    def __init__(self, idx, ty, val):
        self.idx, self.ty, self.val = idx, ty, val

    def render(self):
        return "v%d" % self.idx

    def ev(self, ctx):
        return self.val

    def has_unsigned(self):
        return not signed(self.ty)


class Lit(Node):
    def __init__(self, v, hexa):
        self.v, self.hexa = v, hexa

    def render(self):
        return ("0x%X" % self.v) if self.hexa else str(self.v)

    def ev(self, ctx):
        return self.v

    def has_unsigned(self):
        return False


class Shift(Node):
    """`(v op k)`: a leaf of the left operand's own type; bits shifted out of that type are lost."""

    def __init__(self, var, op, k):
        self.var, self.op, self.k = var, op, k

    def render(self):
        return "(%s %s %d)" % (self.var.render(), self.op, self.k)

    def ev(self, ctx):
        t = self.var.ty
        if self.op == "<<":
            return wrap(self.var.val << self.k, t)
        return self.var.val >> self.k

    def has_unsigned(self):
        return not signed(self.var.ty)


class Un(Node):
    def __init__(self, op, x):
        self.op, self.x = op, x

    def render(self):
        return "(%s%s)" % (self.op, self.x.render())

    def ev(self, ctx):
        v = self.x.ev(ctx)
        r = -v if self.op == "-" else ~v
        if not (lo(ctx) <= r <= hi(ctx)):
            raise Reject()
        return r

    def has_unsigned(self):
        return self.x.has_unsigned()


class Bin(Node):
    def __init__(self, op, l, r):
        self.op, self.l, self.r = op, l, r

    def render(self):
        return "(%s %s %s)" % (self.l.render(), self.op, self.r.render())

    def ev(self, ctx):
        a, b = self.l.ev(ctx), self.r.ev(ctx)
        if self.op == "+":
            r = a + b
        elif self.op == "-":
            r = a - b
        elif self.op == "*":
            r = a * b
        elif self.op == "/":
            if b == 0:
                raise Reject()
            r = trunc_div(a, b)
        elif self.op == "%":
            if b == 0:
                raise Reject()
            r = a - trunc_div(a, b) * b
        elif self.op == "&":
            r = a & b
        elif self.op == "|":
            r = a | b
        else:
            r = a ^ b
        if not (lo(ctx) <= r <= hi(ctx)):
            raise Reject()
        return r

    def has_unsigned(self):
        return self.l.has_unsigned() or self.r.has_unsigned()


def rand_val(rng, ty, ctx):
    mn, mx = lo(ty), hi(ty)
    pick = rng.random()
    if ty == ctx and bits(ty) <= 32:
        # a ctx-wide leaf must leave headroom, otherwise almost every tree overflows
        span = (mx - mn) // 8
        return rng.randint(max(mn, -span) if signed(ty) else 0, min(mx, span))
    if pick < 0.30:
        return rng.choice([mn, mx, 0, 1] + ([-1, mn + 1] if signed(ty) else [mx - 1]))
    if pick < 0.55:
        return rng.randint(max(mn, -300), min(mx, 300))
    return rng.randint(mn, mx)


def build_tree(rng, ctx, leaves, state, depth):
    """Random tree; `state` collects the Var leaves.  Raises Reject for ill-formed combinations."""
    if depth == 0 or rng.random() < 0.28:
        r = rng.random()
        if r < 0.22:
            return Lit(rng.choice([1, 2, 3, 4, 5, 6, 7, 9, 10, 16, 100]), rng.random() < 0.2)
        ty = rng.choice(leaves)
        var = Var(len(state), ty, rand_val(rng, ty, ctx))
        state.append(var)
        if rng.random() < 0.12 and ty != ctx:
            k = rng.randint(0, min(bits(ty) - 1, 40))
            return Shift(var, rng.choice(["<<", ">>"]), k)
        return var
    r = rng.random()
    if r < 0.12 and signed(ctx):
        sub = build_tree(rng, ctx, leaves, state, depth - 1)
        if isinstance(sub, (Var, Shift)) and sub.has_unsigned():
            raise Reject()           # `-b8` is rejected (unary minus on unsigned); `~b8` has no specified width
        if isinstance(sub, Lit):
            raise Reject()
        op = rng.choice(["-", "~"])
        if op == "~" and sub.has_unsigned():
            raise Reject()           # width of ~ on a narrow unsigned operand inside a wider tree is unspecified
        return Un(op, sub)
    op = rng.choice(["+", "+", "-", "-", "*", "*", "/", "%", "&", "|", "^"])
    return Bin(op, build_tree(rng, ctx, leaves, state, depth - 1), build_tree(rng, ctx, leaves, state, depth - 1))


def reject_literal_only(node):
    return isinstance(node, (Lit,))


def gen_trees(ctx, count, seed):
    rng = random.Random(seed)
    leaves = CTX_LEAVES[ctx]
    cases = []
    attempts = 0
    while len(cases) < count and attempts < 200000:
        attempts += 1
        state = []
        try:
            tree = build_tree(rng, ctx, leaves, state, rng.choice([2, 3, 3, 4]))
            if isinstance(tree, (Lit, Var)) or len(state) < 2:
                continue
            if len(set(v.ty for v in state)) < 2 and rng.random() < 0.7:
                continue                      # prefer genuinely mixed-width trees
            value = tree.ev(ctx)
            if not (lo(ctx) <= value <= hi(ctx)):
                continue
        except Reject:
            continue
        cases.append((tree, state, value))
    return cases


def gen_trees_file(ctx, seed):
    name = "trees_%s" % ctx
    cases = gen_trees(ctx, 70, seed)
    p = Program(name)
    for i, (tree, state, value) in enumerate(cases):
        params = ", ".join("v%d: %s" % (v.idx, v.ty) for v in state)
        p.decl("fn t%d(%s) -> %s {\n    let r: %s = %s;\n    r\n}\n" % (i, params, ctx, ctx, tree.render()))
        args = ", ".join(lit(v.val, v.ty) for v in state)
        p.bad("t%d(%s) != %s" % (i, args, lit(value, ctx)))
    assert len(cases) >= 60, (ctx, len(cases))
    return p.render()


