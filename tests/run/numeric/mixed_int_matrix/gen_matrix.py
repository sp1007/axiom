# Shifts: count of every integer type (AXS-INT-021: only the left operand type matters), exact results
# ---------------------------------------------------------------------------------------------------------------
def gen_shift():
    p = Program("shift_counts")
    left_types = ["i8", "u8", "i16", "u16", "i32", "u32", "i64", "u64", "i128", "u128", "isize", "usize"]
    count_types = [t[0] for t in TYPES]
    for a in left_types:
        for c in count_types:
            sfx = "%s_%s" % (a, c)
            p.decl("fn shl_%s(x: %s, n: %s) -> %s { x << n }\nfn shr_%s(x: %s, n: %s) -> %s { x >> n }\n" % (sfx, a, c, a, sfx, a, c, a))
            for x in (1, hi(a), lo(a), 0x5A & hi(a) if hi(a) >= 0x5A else 1):
                for n in (0, 1, bits(a) - 1):
                    if n > hi(c):
                        continue
                    p.bad("shl_%s(%s, %s) != %s" % (sfx, lit(x, a), lit(n, c), lit(wrap(x << n, a), a)))
                    p.bad("shr_%s(%s, %s) != %s" % (sfx, lit(x, a), lit(n, c), lit(x >> n, a)))
    return p.render()


def gen_shift_trap(a, c, n, which):
    what = {"hi": "count == BITS", "neg": "negative count", "big": "count == 2^32 + BITS"}[which]
    return "\n".join([
        "// test: run", "// exit: 101", "// stdout: before\\n", "// stderr-contains: shift amount out of range", GEN,
        "// %s, left %s, count type %s: must trap in every mode (a count truncated to a narrower type would not)." % (what, a, c),
        "",
        "fn sh(x: %s, n: %s) -> %s {" % (a, c, a),
        "    x << n",
        "}", "",
        "fn main() -> i32 {",
        "    print(\"before\\n\");",
        "    let r: %s = sh(%s, %s);" % (a, lit(1, a), lit(n, c)),
        "    if r == %s { return 7; }" % lit(1, a),
        "    print(\"UNREACHABLE\\n\");",
        "    0",
        "}", ""])


