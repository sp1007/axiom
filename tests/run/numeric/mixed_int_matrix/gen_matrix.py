#!/usr/bin/env python3
"""T455 generator: REQ-OWNER-007 Pattern D mixed-width integer matrix (tests/run/numeric/mixed_int_matrix/).

Every expected value is computed here with exact Python integers following SPEC-40 AXS-INT-050..054, never by the
compiler.  The model:

  * `join(A, B)` of the two operand types of one binary operator is AXS-INT-051 (same signedness: the wider type; narrower
    unsigned + wider signed: the signed type; narrower signed + wider unsigned: the smallest wider signed type
    (u16 -> i32, u32 -> i64, u64/usize -> i128); equal width with opposite signedness and u128 + signed: undefined).
  * inside an arithmetic tree whose declared context type is C (`let r: C = <tree>`), every node is evaluated in C
    (AXS-INT-052: `b8 * 2` is 400, not a u8 overflow); a shift is a leaf of its left operand's own type, with the
    bits shifted out of that type lost; the generator rejects any tree in which an intermediate leaves C's range.
  * a comparison / arithmetic of two leaves is evaluated mathematically (the join type is lossless).

    python gen_matrix.py            write the files
    python gen_matrix.py --check    verify the files are current (writes nothing)
"""

import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GEN = "// GENERATED by tests/run/numeric/mixed_int_matrix/gen_matrix.py (T455). Do not edit by hand."

TYPES = [
    ("i8", 8, True), ("i16", 16, True), ("i32", 32, True), ("i64", 64, True), ("i128", 128, True), ("isize", 64, True),
    ("u8", 8, False), ("u16", 16, False), ("u32", 32, False), ("u64", 64, False), ("u128", 128, False),
    ("usize", 64, False),
]
BY = {t[0]: t for t in TYPES}
CHUNK = 12


def bits(n):
    return BY[n][1]


def signed(n):
    return BY[n][2]


def lo(n):
    return -(1 << (bits(n) - 1)) if signed(n) else 0


def hi(n):
    return (1 << (bits(n) - 1)) - 1 if signed(n) else (1 << bits(n)) - 1


def wrap(v, n):
    v &= (1 << bits(n)) - 1
    if signed(n) and v >= (1 << (bits(n) - 1)):
        v -= 1 << bits(n)
    return v


def lit(v, n):
    return "(-%d%s)" % (-v, n) if v < 0 else "%d%s" % (v, n)


def sgn_of_bits(b):
    return {8: "i8", 16: "i16", 32: "i32", 64: "i64", 128: "i128"}[b]


def join(a, b):
    """AXS-INT-051 for two distinct-or-equal operand types; None when undefined (rejected by the compiler)."""
    if a == b:
        return a
    sa, sb = signed(a), signed(b)
    ba, bb = bits(a), bits(b)
    if sa == sb:
        if ba != bb:
            return a if ba > bb else b
        return None   # i64/isize and u64/usize pairs are not part of the matrix (the result type depends on context)
    s, u = (a, b) if sa else (b, a)
    if bits(s) > bits(u):
        return s
    if bits(s) < bits(u):
        return {16: "i32", 32: "i64", 64: "i128"}.get(bits(u))
    return None


def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def values(n):
    mn, mx = lo(n), hi(n)
    if signed(n):
        return [mn, -1, 0, 1, mx]
    return [0, 1, mx >> 1, mx]


class Program:
    def __init__(self, name):
        self.name = name
        self.decls = []     # helper functions
        self.checks = []    # statements `if <bad condition> { return k; }`

    def decl(self, text):
        self.decls.append(text)

    def bad(self, cond):
        self.checks.append(cond)

    def render(self):
        out = ["// test: run", "// stdout: OK %s\\n" % self.name, GEN, ""]
        out.extend(self.decls)
        n = (len(self.checks) + CHUNK - 1) // CHUNK
        for c in range(n):
            out.append("fn chunk_%d() -> i32 {" % c)
            for k, cond in enumerate(self.checks[c * CHUNK:(c + 1) * CHUNK], 1):
                out.append("    if %s { return %d; }" % (cond, k))
            out.append("    0")
            out.append("}")
            out.append("")
        out.append("fn main() -> i32 {")
        for c in range(n):
            out.append("    let r%d: i32 = chunk_%d();" % (c, c))
            out.append("    if r%d != 0 { print(\"FAIL chunk %d case \"); print_int(r%d as i64); print(\"\\n\"); return %d; }" % (c, c, c, c + 1))
        out.append("    print(\"OK %s\\n\");" % self.name)
        out.append("    0")
        out.append("}")
        return "\n".join(out) + "\n"


