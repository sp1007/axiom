#!/usr/bin/env python3
"""Generator for the T164 (AX0-FIX-10, ADR-0043 §2, INV-BOOT-005) symbol-id-space regression.

Writes `many_symbols.ax`: a program with more than 30100 user symbols, then generic functions
`fn gid_<k><T>(x: T) -> T`, then kernel32 externs and std functions that are called from `main`.

Why this shape: before T164 axiom0 and axiomc numbered user symbols from 1, std symbols from 10000 and
extern symbols from 30000. The resolver allocates item and enum-variant ids in its collection pass and
generic parameters / parameters / locals in its body pass, so the `T` and `x` ids of the generic functions
land on 29800..30400 -- the window of the extern ids 30000.. -- and a call of such an extern was typed as a
call of the type parameter (`AX_TYPE_NOT_CALLABLE`, T444 report B2). With the single counter no two
symbols share an id whatever the program size.

The direct extern calls cannot run in the interpreter oracle (ADR-0002, `AX_FFI_NOT_IN_ORACLE`), so they sit
behind a runtime condition that is never true (`sum == 7`); type checking and native code
generation of the calls are what the regression needs. Everything printed is computed in all modes.

Python 3 stdlib only.

Usage:
  python tests/run/symbol_id_space/gen_symbol_id_space.py           # write many_symbols.ax
  python tests/run/symbol_id_space/gen_symbol_id_space.py --check   # exit 1 if the file differs
  python tests/run/symbol_id_space/gen_symbol_id_space.py --axiom0 <path>   # variant without std.core.cmp
                                                                  # (the frozen axiom0 cannot load it)
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "many_symbols.ax")

PRELUDE_SYMBOLS = 28      # 24 prelude names + 4 synthetic Fn traits (ids 1..28 since T164)
ENUMS = 576               # each enum: 1 item symbol + VARIANTS variant symbols
VARIANTS = 50
GENERICS = 300            # each generic fn: 1 item symbol (collection) + T + x (body pass)
MAX_BYTES = 1 << 20

EXTERNS = [
    ("GetCurrentProcessId", "", "u32"),
    ("GetCurrentThreadId", "", "u32"),
    ("GetTickCount", "", "u32"),
    ("GetLastError", "", "u32"),
    ("GetStdHandle", "n: u32", "usize"),
    ("CloseHandle", "h: usize", "i32"),
]


def generate(with_std=True):
    """with_std=False drops the std.core.cmp part: the frozen axiom0 cannot load that module on demand, so that
    variant (written only by `--axiom0 <path>`, never committed) is the baseline evidence for axiom0."""
    out = []
    w = out.append
    w("// test: run")
    w("// modes: interp native")
    w("// timeout: 600")
    cmp_line = "cmp -1 1 0\\n" if with_std else ""
    w("// stdout: enums 576 last 49\\ngid 45150\\n" + cmp_line + "std 7\\ndone\\n")
    w("// T164 (AX0-FIX-10, ADR-0043 §2, INV-BOOT-005): more than 30100 user symbols, then generic functions")
    w("// whose type-parameter ids fell on the old extern ids 30000.., then kernel32 extern calls and std calls.")
    w("// GENERATED by gen_symbol_id_space.py -- do not edit; run the generator (with --check in CI).")
    w("")
    if with_std:
        w("use std.core.cmp.Ord")
        w("use std.core.cmp.Ordering")
        w("")
    for e in range(ENUMS):
        variants = ", ".join("V%d" % v for v in range(VARIANTS))
        w("enum E%d { %s }" % (e, variants))
    w("")
    for k in range(GENERICS):
        w("fn gid_%d<T>(x: T) -> T {" % k)
        w("    x")
        w("}")
    w("")
    w('@link("kernel32")')
    w('extern "system" {')
    for name, params, ret in EXTERNS:
        w("    fn %s(%s) -> %s;" % (name, params, ret))
    w("}")
    w("")
    w("fn last_variant(e: E%d) -> i64 {" % (ENUMS - 1))
    w("    match e {")
    w("        E%d.V0 => 0," % (ENUMS - 1))
    w("        E%d.V%d => %d," % (ENUMS - 1, VARIANTS - 1, VARIANTS - 1))
    w("        _ => 1,")
    w("    }")
    w("}")
    w("")
    if with_std:
        w("fn ord_score<T: Ord>(a: view<T>, b: view<T>) -> i64 {")
        w("    match a.cmp(b) {")
        w("        Ordering.Less => -1,")
        w("        Ordering.Equal => 0,")
        w("        Ordering.Greater => 1,")
        w("    }")
        w("}")
        w("")
    w("fn call_externs() -> u32 {")
    w("    let pid: u32 = unsafe { GetCurrentProcessId() };")
    w("    let tid: u32 = unsafe { GetCurrentThreadId() };")
    w("    let ticks: u32 = unsafe { GetTickCount() };")
    w("    let err: u32 = unsafe { GetLastError() };")
    w("    let h: usize = unsafe { GetStdHandle(4294967285u32) };")
    w("    let closed: i32 = unsafe { CloseHandle(0) };")
    w("    pid + tid + ticks + err + (h as u32) + (closed as u32)")
    w("}")
    w("")
    w("fn main() -> i32 {")
    w('    print("enums ")')
    w("    print_int(%di64)" % ENUMS)
    w('    print(" last ")')
    w("    print_int(last_variant(E%d.V%d))" % (ENUMS - 1, VARIANTS - 1))
    w('    print("\\n")')
    w("    let mut sum: i64 = 0")
    total = 0
    for k in range(GENERICS):
        w("    sum = sum + gid_%d(%di64)" % (k, k + 1))
        total += k + 1
    w('    print("gid ")')
    w("    print_int(sum)")
    w('    print("\\n")')
    if with_std:
        w("    let x: u32 = 3")
        w("    let y: u32 = 9")
        w("    let d: i64 = match x.cmp(view(y)) {")
        w("        Ordering.Less => -1,")
        w("        Ordering.Equal => 0,")
        w("        Ordering.Greater => 1,")
        w("    }")
        w('    print("cmp ")')
        w("    print_int(d)")
        w('    print(" ")')
        w("    print_int(ord_score(view(y), view(x)))")
        w('    print(" ")')
        w("    print_int(ord_score(view(x), view(x)))")
        w('    print("\\n")')
    w("    let b: bool = gid_0(true)")
    w("    let u: u8 = gid_1(7u8)")
    w("    if sum == 7i64 {")
    w("        let _x = call_externs()")
    w("    }")
    w("    if b {")
    w('        print("std ")')
    w("        print_int(u as i64)")
    w('        print("\\n")')
    w("    }")
    w('    print("done\\n")')
    w("    return 0")
    w("}")
    assert total == 45150, total
    text = "\n".join(out) + "\n"
    return text.encode("utf-8")


def user_symbol_estimate():
    collected = ENUMS * (1 + VARIANTS) + GENERICS + 3  # + last_variant, call_externs, main
    body = GENERICS * 2 + 1 + 6 + 3                     # T, x per generic; params/locals of the rest
    return PRELUDE_SYMBOLS + collected + body


def main(argv):
    data = generate()
    if len(data) > MAX_BYTES:
        print("many_symbols.ax is %d bytes, over the 1 MB limit" % len(data), file=sys.stderr)
        return 2
    if user_symbol_estimate() <= 30100:
        print("fewer than 30100 user symbols", file=sys.stderr)
        return 2
    if "--axiom0" in argv[1:]:
        i = argv.index("--axiom0")
        if i + 1 >= len(argv):
            print("--axiom0 needs an output path", file=sys.stderr)
            return 2
        with open(argv[i + 1], "wb") as f:
            f.write(generate(with_std=False))
        print("wrote axiom0 variant %s" % argv[i + 1])
        return 0
    if "--check" in argv[1:] or "check" in argv[1:]:
        try:
            with open(OUT, "rb") as f:
                cur = f.read()
        except OSError:
            cur = None
        if cur != data:
            print("DIFFERS %s" % OUT)
            return 1
        print("OK %s" % OUT)
        return 0
    with open(OUT, "wb") as f:
        f.write(data)
    print("wrote %s (%d bytes, ~%d user symbols)" % (OUT, len(data), user_symbol_estimate()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
