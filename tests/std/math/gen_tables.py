#!/usr/bin/env python3
"""Generates std/math/tables.ax (T461) from mathtables.py.

    python tests/std/math/gen_tables.py            rewrite std/math/tables.ax
    python tests/std/math/gen_tables.py --check    fail when the file is stale

Every number is a mathematical constant computed with mpmath (see mathtables.py); nothing is copied from another library.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import mathtables as T  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "std", "math", "tables.ax")
OUT64 = os.path.join(ROOT, "std", "math", "f64", "consts.ax")
OUT32 = os.path.join(ROOT, "std", "math", "f32", "consts.ax")

CONST_ORDER = ["PI", "TAU", "E", "LN_2", "LN_10", "LOG2_E", "LOG10_E", "SQRT_2", "FRAC_1_SQRT_2", "FRAC_PI_2", "FRAC_PI_3",
               "FRAC_PI_4", "FRAC_PI_6", "FRAC_PI_8", "FRAC_1_PI", "FRAC_2_PI", "FRAC_2_SQRT_PI"]


def lit(x):
    r = repr(float(x))
    if "e" in r:
        mant, exp = r.split("e")
        sign = "-" if exp.startswith("-") else ""
        digits = exp.lstrip("+-").lstrip("0") or "0"
        r = mant + "e" + sign + digits
    elif "." not in r:
        r = r + ".0"
    return r


def dd(pair):
    return "Dd { hi: %s, lo: %s }" % (lit(pair[0]), lit(pair[1]))


def emit_dd_array(lines, name, comment, items):
    lines.append("// " + comment)
    lines.append("pub const %s: [%d]Dd = [" % (name, len(items)))
    for it in items:
        lines.append("    " + dd(it) + ",")
    lines.append("];")
    lines.append("")


def build():
    L = []
    L.append("module std.math.tables")
    L.append("")
    L.append("// GENERATED by tests/std/math/gen_tables.py from mathtables.py (T461). Do not edit.")
    L.append("// Mathematical constants of std.math computed with mpmath at 400 bits: double-double splits, Taylor")
    L.append("// coefficients, the reduction tables of log and atan and the bits of 2/pi (Payne-Hanek).")
    L.append("")
    L.append("use std.math.dd.Dd")
    L.append("")
    ln2 = T.ln2_parts()
    L.append("// ln 2 = LN2_HI + LN2_MID + LN2_LO; LN2_HI has 40 significant bits so that k * LN2_HI is exact for |k| < 2^13.")
    L.append("pub const LN2_HI: f64 = %s;" % lit(ln2[0]))
    L.append("pub const LN2_MID: f64 = %s;" % lit(ln2[1]))
    L.append("pub const LN2_LO: f64 = %s;" % lit(ln2[2]))
    L.append("")
    dds = T.dd_consts()
    for name in ["PI", "PIO2", "LN2", "LOG2E", "LOG10E", "LN10", "TWO_OVER_SQRT_PI", "ONE_OVER_SQRT_PI"]:
        L.append("pub const %s_DD: Dd = %s;" % (name, dd(dds[name])))
    L.append("")
    emit_dd_array(L, "SINC", "sin(y) = y * sum SINC[k] y^(2k), SINC[k] = (-1)^k / (2k+1)!", T.sin_coefs(14))
    emit_dd_array(L, "COSC", "cos(y) = sum COSC[k] y^(2k), COSC[k] = (-1)^k / (2k)!", T.cos_coefs(15))
    emit_dd_array(L, "EXPM1C", "expm1(w) = w * sum EXPM1C[k] w^k, EXPM1C[k] = 1 / (k+1)!", T.expm1_coefs(11))
    emit_dd_array(L, "ATANC", "atan(z) = z * sum ATANC[k] z^(2k), ATANC[k] = (-1)^k / (2k+1)", T.atan_coefs(8))
    emit_dd_array(L, "ATANHC", "log((1+s)/(1-s)) = 2 s sum ATANHC[k] s^(2k), ATANHC[k] = 1 / (2k+1)", T.atanh_coefs(8))
    emit_dd_array(L, "ATANT", "atan(i / 16), i = 0..16", T.atan_table())
    L.append("pub struct LogEntry {")
    L.append("    pub invc: f64,")
    L.append("    pub logc: Dd,")
    L.append("}")
    L.append("")
    L.append("// Reduction table of log: for index i of the bit pattern of x (see log_core), invc is 1 / c rounded to a")
    L.append("// double, c the midpoint of the interval of index i, and logc = -log(invc) as a double-double.")
    L.append("pub const LOGT: [%d]LogEntry = [" % T.LOG_N)
    for invc, h, l in T.log_table():
        L.append("    LogEntry { invc: %s, logc: Dd { hi: %s, lo: %s } }," % (lit(invc), lit(h), lit(l)))
    L.append("];")
    L.append("")
    words = T.two_over_pi_words()
    L.append("// The binary expansion of 2/pi = 0.b1 b2 b3 ...; word i holds bits 64i+1 .. 64i+64.")
    L.append("pub const TWO_OVER_PI: [%d]u64 = [" % len(words))
    for w in words:
        L.append("    0x%016Xu64," % w)
    L.append("];")
    L.append("")
    return "\n".join(L)


def build_consts(ty):
    import mpmath
    L = []
    L.append("module std.math.%s.consts" % ty)
    L.append("")
    L.append("// GENERATED by tests/std/math/gen_tables.py (T461). Do not edit.")
    L.append("// The correctly rounded %s constants of SPEC-41 AXS-FLT-061; `std.math` re-exports the f64 ones." % ty)
    L.append("")
    for name in CONST_ORDER:
        text = mpmath.nstr(T.CONSTS[name], 36, strip_zeros=False)
        L.append("pub const %s: %s = %s;" % (name, ty, text))
    L.append("")
    return chr(10).join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    outputs = [(OUT, build()), (OUT64, build_consts("f64")), (OUT32, build_consts("f32"))]
    bad = 0
    for path, text in outputs:
        if args.check:
            try:
                with open(path, "rb") as f:
                    cur = f.read().decode("utf-8")
            except OSError:
                print("missing " + path)
                bad = 1
                continue
            if cur != text:
                print("stale " + path)
                bad = 1
            else:
                print("ok " + path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as f:
                f.write(text.encode("utf-8"))
            print("wrote " + path)
    return bad


if __name__ == "__main__":
    sys.exit(main())
