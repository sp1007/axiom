def prog_checked():
    p = Prog("checked", NUM)
    for t in TYS:
        p.helpers.extend(opt_helper(t))
    for t in TYS:
        for op in ("add", "sub", "mul", "div", "rem"):
            p.start("test_checked_%s_%s" % (op, t.name))
            for a, b in t.pairs():
                if op == "add":
                    r = a + b
                elif op == "sub":
                    r = a - b
                elif op == "mul":
                    r = a * b
                elif op == "div":
                    r = None if b == 0 else tdiv(a, b)
                else:
                    # SPEC-40 AXS-INT-024: MIN % -1 is None for signed types even though the remainder is 0
                    r = None if b == 0 or (t.signed and a == t.min and b == -1) else trem(a, b)
                if r is not None and not t.inr(r):
                    r = None
                p.check(chk_call(t, "%s.checked_%s(%s)" % (t.recv(a), op, t.lit(b)), r))
            p.end()
        # unary: neg, abs
        p.start("test_checked_neg_abs_%s" % t.name)
        for a in t.values():
            r = -a
            p.check(chk_call(t, "%s.checked_neg()" % t.recv(a), r if t.inr(r) else None))
            if t.signed:
                r = abs(a)
                p.check(chk_call(t, "%s.checked_abs()" % t.recv(a), r if t.inr(r) else None))
        p.end()
        # shifts
        counts = [0, 1, t.bits // 2, t.bits - 1, t.bits, t.bits + 1, 200]
        p.start("test_checked_shift_%s" % t.name)
        for a in t.values():
            for c in counts:
                rl = t.wrap(a << c) if c < t.bits else None
                rr = (a >> c) if c < t.bits else None
                p.check(chk_call(t, "%s.checked_shl(%du32)" % (t.recv(a), c), rl))
                p.check(chk_call(t, "%s.checked_shr(%du32)" % (t.recv(a), c), rr))
        p.end()
        # pow
        p.start("test_checked_pow_%s" % t.name)
        bases = [b for b in (0, 1, 2, 3, 10, -1, -2, -3, t.max, t.min, 7) if t.inr(b)]
        exps = [0, 1, 2, 3, 5, 6, 7, 8, 15, 31, 32, 63, 64, 127, 128]
        for b in bases:
            for e in exps:
                r = b ** e
                p.check(chk_call(t, "%s.checked_pow(%du32)" % (t.recv(b), e), r if t.inr(r) else None))
        p.end()
    return p


def prog_overflowing():
    p = Prog("overflowing", NUM)
    for t in TYS:
        for op in ("add", "sub", "mul"):
            p.start("test_overflowing_%s_%s" % (op, t.name))
            for a, b in t.pairs():
                r = {"add": a + b, "sub": a - b, "mul": a * b}[op]
                v = t.wrap(r)
                f = not t.inr(r)
                p.check_block("let r = %s.overflowing_%s(%s);" % (t.recv(a), op, t.lit(b)),
                              "r.0 != %s || r.1 != %s" % (t.lit(v), bool_lit(f)))
            p.end()
        for op in ("div", "rem"):
            p.start("test_overflowing_%s_%s" % (op, t.name))
            for a, b in t.pairs():
                if b == 0:
                    continue
                q = tdiv(a, b) if op == "div" else trem(a, b)
                if not t.inr(tdiv(a, b)):  # MIN / -1
                    v, f = (t.min if op == "div" else 0), True
                else:
                    v, f = q, False
                p.check_block("let r = %s.overflowing_%s(%s);" % (t.recv(a), op, t.lit(b)),
                              "r.0 != %s || r.1 != %s" % (t.lit(v), bool_lit(f)))
            p.end()
        p.start("test_overflowing_unary_%s" % t.name)
        for a in t.values():
            v = t.wrap(-a)
            f = (a == t.min) if t.signed else (a != 0)
            p.check_block("let r = %s.overflowing_neg();" % t.recv(a), "r.0 != %s || r.1 != %s" % (t.lit(v), bool_lit(f)))
            if t.signed:
                v = t.wrap(abs(a))
                f = a == t.min
                p.check_block("let r = %s.overflowing_abs();" % t.recv(a), "r.0 != %s || r.1 != %s" % (t.lit(v), bool_lit(f)))
        p.end()
        counts = [0, 1, t.bits // 2, t.bits - 1, t.bits, t.bits + 1, 200]
        p.start("test_overflowing_shift_%s" % t.name)
        for a in t.values():
            for c in counts:
                vl = t.wrap(a << (c % t.bits))
                vr = a >> (c % t.bits)
                f = c >= t.bits
                p.check_block("let r = %s.overflowing_shl(%du32);" % (t.recv(a), c), "r.0 != %s || r.1 != %s" % (t.lit(vl), bool_lit(f)))
                p.check_block("let r = %s.overflowing_shr(%du32);" % (t.recv(a), c), "r.0 != %s || r.1 != %s" % (t.lit(vr), bool_lit(f)))
        p.end()
        p.start("test_overflowing_pow_%s" % t.name)
        bases = [b for b in (0, 1, 2, 3, -1, -2, 10, t.max, t.min) if t.inr(b)]
        for b in bases:
            for e in (0, 1, 2, 3, 7, 8, 31, 64, 127):
                r = b ** e
                p.check_block("let r = %s.overflowing_pow(%du32);" % (t.recv(b), e),
                              "r.0 != %s || r.1 != %s" % (t.lit(t.wrap(r)), bool_lit(not t.inr(r))))
        p.end()
    return p


def sat(t, x):
    return max(t.min, min(t.max, x))


def prog_wrapping_saturating():
    p = Prog("wrapping_saturating", NUM)
    for t in TYS:
        p.start("test_wrapping_%s" % t.name)
        for a, b in t.pairs():
            for op in ("add", "sub", "mul"):
                r = {"add": a + b, "sub": a - b, "mul": a * b}[op]
                p.check("%s.wrapping_%s(%s) != %s" % (t.recv(a), op, t.lit(b), t.lit(t.wrap(r))))
            if b != 0:
                qd = tdiv(a, b)
                p.check("%s.wrapping_div(%s) != %s" % (t.recv(a), t.lit(b), t.lit(t.wrap(qd))))
                rr = trem(a, b) if t.inr(qd) else 0
                p.check("%s.wrapping_rem(%s) != %s" % (t.recv(a), t.lit(b), t.lit(rr)))
        for a in t.values():
            p.check("%s.wrapping_neg() != %s" % (t.recv(a), t.lit(t.wrap(-a))))
            if t.signed:
                p.check("%s.wrapping_abs() != %s" % (t.recv(a), t.lit(t.wrap(abs(a)))))
            for c in (0, 1, t.bits - 1, t.bits, t.bits + 3, 200):
                p.check("%s.wrapping_shl(%du32) != %s" % (t.recv(a), c, t.lit(t.wrap(a << (c % t.bits)))))
                p.check("%s.wrapping_shr(%du32) != %s" % (t.recv(a), c, t.lit(a >> (c % t.bits))))
        for b in [x for x in (0, 1, 2, 3, -1, -2, 7, t.max, t.min) if t.inr(x)]:
            for e in (0, 1, 2, 3, 7, 8, 31, 64, 127, 128):
                p.check("%s.wrapping_pow(%du32) != %s" % (t.recv(b), e, t.lit(t.wrap(b ** e))))
        p.end()
        p.start("test_saturating_%s" % t.name)
        for a, b in t.pairs():
            for op in ("add", "sub", "mul"):
                r = {"add": a + b, "sub": a - b, "mul": a * b}[op]
                p.check("%s.saturating_%s(%s) != %s" % (t.recv(a), op, t.lit(b), t.lit(sat(t, r))))
            if b != 0:
                p.check("%s.saturating_div(%s) != %s" % (t.recv(a), t.lit(b), t.lit(sat(t, tdiv(a, b)))))
        if t.signed:
            for a in t.values():
                p.check("%s.saturating_neg() != %s" % (t.recv(a), t.lit(sat(t, -a))))
                p.check("%s.saturating_abs() != %s" % (t.recv(a), t.lit(sat(t, abs(a)))))
        for b in [x for x in (0, 1, 2, 3, -1, -2, -3, 7, t.max, t.min) if t.inr(x)]:
            for e in (0, 1, 2, 3, 7, 8, 31, 64, 127, 128):
                p.check("%s.saturating_pow(%du32) != %s" % (t.recv(b), e, t.lit(sat(t, b ** e))))
        p.end()
    return p


def prog_misc():
    p = Prog("misc", NUM)
    for t in TYS:
        p.start("test_misc_%s" % t.name)
        # associated constants (compiler built-ins) and the module's ordering helpers
        p.check("%s.MIN != %s" % (t.name, t.lit(t.min)))
        p.check("%s.MAX != %s" % (t.name, t.lit(t.max)))
        p.check("%s.BITS != %du32" % (t.name, t.bits))
        vals = t.values()
        for a, b in t.pairs():
            p.check("%s.min(%s) != %s" % (t.recv(a), t.lit(b), t.lit(min(a, b))))
            p.check("%s.max(%s) != %s" % (t.recv(a), t.lit(b), t.lit(max(a, b))))
            d = abs(a - b)
            ut = t.ut
            p.check("%s.abs_diff(%s) != %d%s" % (t.recv(a), t.lit(b), d, ut))
        for a in vals:
            lo = vals[1] if len(vals) > 2 else vals[0]
            hi = vals[-2]
            p.check("%s.clamp(%s, %s) != %s" % (t.recv(a), t.lit(lo), t.lit(hi), t.lit(max(lo, min(hi, a)))))
            if t.signed:
                u = abs(a)
                p.check("%s.unsigned_abs() != %d%s" % (t.recv(a), u, t.ut))
                sg = (a > 0) - (a < 0)
                p.check("%s.signum() != %s" % (t.recv(a), t.lit(sg)))
                p.check("%s.is_positive() != %s" % (t.recv(a), bool_lit(a > 0)))
                p.check("%s.is_negative() != %s" % (t.recv(a), bool_lit(a < 0)))
                if a != t.min:
                    p.check("%s.abs() != %s" % (t.recv(a), t.lit(abs(a))))
        # pow without overflow
        for b in [x for x in (0, 1, 2, 3, -1, -2, 7) if t.inr(x)]:
            for e in (0, 1, 2, 3, 5, 6):
                r = b ** e
                if t.inr(r):
                    p.check("%s.pow(%du32) != %s" % (t.recv(b), e, t.lit(r)))
        p.end()
    return p


def pat_values(t):
    s = {0, 1, 2, 3, 4, 5, 0x55, 0xAA, 0x7F, 0x80, 0xFF, t.max, t.max - 1, t.max // 2, 0x0123456789ABCDEF & t.mask,
         0x8040201008040201 & t.mask, 0xF0F0F0F0F0F0F0F0 & t.mask, 0x1234 & t.mask}
    if t.bits == 128:
        s.add(0x0123456789ABCDEF0011223344556677)
        s.add(1 << 100)
        s.add((1 << 64) - 1)
        s.add(1 << 64)
    # reinterpret as signed where needed
    out = set()
    for v in s:
        v &= t.mask
        out.add(t.wrap(v))
    out.add(t.wrap(t.mask))
    out.add(t.min)
    return sorted(v for v in out if t.inr(v))


def popcount(t, v):
    return bin(v & t.mask).count("1")


def lz(t, v):
    u = v & t.mask
    return t.bits - u.bit_length()


def tz(t, v):
    u = v & t.mask
    if u == 0:
        return t.bits
    return (u & -u).bit_length() - 1


def rotl(t, v, n):
    u = v & t.mask
    n %= t.bits
    return t.wrap(((u << n) | (u >> (t.bits - n))) & t.mask) if n else t.wrap(u)


def bswap(t, v):
    u = v & t.mask
    return t.wrap(int.from_bytes(u.to_bytes(t.bits // 8, "little"), "big"))


def brev(t, v):
    u = v & t.mask
    return t.wrap(int(format(u, "0%db" % t.bits)[::-1], 2))


def prog_bits():
    p = Prog("bits", NUM)
    for t in TYS:
        for fam in ("count", "rotate", "bytes"):
            p.start("test_bits_%s_%s" % (fam, t.name))
            for v in pat_values(t):
                r = t.recv(v)
                if fam == "count":
                    p.check("%s.count_ones() != %du32" % (r, popcount(t, v)))
                    p.check("%s.count_zeros() != %du32" % (r, t.bits - popcount(t, v)))
                    p.check("%s.leading_zeros() != %du32" % (r, lz(t, v)))
                    p.check("%s.trailing_zeros() != %du32" % (r, tz(t, v)))
                    nv = t.wrap(~v)
                    p.check("%s.leading_ones() != %du32" % (r, lz(t, nv)))
                    p.check("%s.trailing_ones() != %du32" % (r, tz(t, nv)))
                elif fam == "rotate":
                    for n in (0, 1, 3, t.bits - 1, t.bits, t.bits + 5, 200):
                        p.check("%s.rotate_left(%du32) != %s" % (r, n, t.lit(rotl(t, v, n))))
                        p.check("%s.rotate_right(%du32) != %s" % (r, n, t.lit(rotl(t, v, (t.bits - (n % t.bits)) % t.bits))))
                else:
                    p.check("%s.swap_bytes() != %s" % (r, t.lit(bswap(t, v))))
                    p.check("%s.reverse_bits() != %s" % (r, t.lit(brev(t, v))))
            p.end()
        if not t.signed:
            p.start("test_pow2_%s" % t.name)
            for v in sorted(set(list(range(0, 18)) + [t.max, t.max // 2, t.max // 2 + 1, (1 << (t.bits - 1)) - 1, 1 << (t.bits - 1),
                                                      (1 << (t.bits - 1)) + 1])):
                if not t.inr(v):
                    continue
                r = t.recv(v)
                p.check("%s.is_power_of_two() != %s" % (r, bool_lit(v != 0 and v & (v - 1) == 0)))
                nxt = 1 if v <= 1 else 1 << (v - 1).bit_length()
                if nxt <= t.max:
                    p.check("%s.next_power_of_two() != %s" % (r, t.lit(nxt)))
                    p.check("!chk_%s(%s.checked_next_power_of_two(), true, %s)" % (t.name, r, t.lit(nxt)))
                else:
                    p.check("!chk_%s(%s.checked_next_power_of_two(), false, 0%s)" % (t.name, r, t.name))
            p.end()
    for t in TYS:
        if not t.signed:
            p.helpers.extend(opt_helper(t))
    return p


def byte_list(t, v):
    return list((v & t.mask).to_bytes(t.bits // 8, "little"))


def prog_bytes():
    p = Prog("bytes", NUM)
    for t in TYS:
        n = t.bits // 8
        p.start("test_bytes_%s" % t.name)
        for v in pat_values(t):
            le = byte_list(t, v)
            be = list(reversed(le))
            r = t.recv(v)
            for fn, arr in (("to_le_bytes", le), ("to_be_bytes", be), ("to_ne_bytes", le)):
                p.emit("let a%d: [%d]u8 = %s.%s();" % (p.case + 1, n, r, fn))
                cond = " || ".join("a%d[%d] != %du8" % (p.case + 1, k, arr[k]) for k in range(n))
                p.check(cond)
            for fn, arr in (("from_le_bytes", le), ("from_be_bytes", be), ("from_ne_bytes", le)):
                lit = "[%s]" % ", ".join("%du8" % x for x in arr)
                p.emit("let b%d: [%d]u8 = %s;" % (p.case + 1, n, lit))
                p.check("%s.%s(b%d) != %s" % (t.name, fn, p.case + 1, t.lit(v)))
        p.end()
    return p


