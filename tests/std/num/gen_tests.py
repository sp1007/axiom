#!/usr/bin/env python3
"""Generator for the T454 integer test programs under tests/std/num/prog and their manifests tests/std/num/*.test.

Every program is a self-checking Axiom program: each case compares a library result with a value computed here
with exact Python integers (SPEC-40 semantics), and returns the 1-based case number as the exit code on the first
mismatch, so a failure points at one line of the generated source.  A program prints `OK <name>` and returns 0
when every case passes.  tests/std/num/num_oracle.py stages the real std sources next to the program and runs it
under the MIR interpreter, native -O0 and native -O1; all three must agree.

    python tests/std/num/gen_tests.py            # (re)write programs and manifests
    python tests/std/num/gen_tests.py --check    # exit 1 when a checked-in file differs

Python 3 standard library only.
"""

import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROG = HERE / "prog"

TYPES = [
    # name, signed, bits, unsigned twin
    ("i8", True, 8, "u8"),
    ("i16", True, 16, "u16"),
    ("i32", True, 32, "u32"),
    ("i64", True, 64, "u64"),
    ("i128", True, 128, "u128"),
    ("isize", True, 64, "usize"),
    ("u8", False, 8, "u8"),
    ("u16", False, 16, "u16"),
    ("u32", False, 32, "u32"),
    ("u64", False, 64, "u64"),
    ("u128", False, 128, "u128"),
    ("usize", False, 64, "usize"),
]


class Ty:
    def __init__(self, name, signed, bits, ut):
        self.name = name
        self.signed = signed
        self.bits = bits
        self.ut = ut
        self.min = -(1 << (bits - 1)) if signed else 0
        self.max = (1 << (bits - 1)) - 1 if signed else (1 << bits) - 1
        self.mask = (1 << bits) - 1

    def wrap(self, x):
        x &= self.mask
        if self.signed and x >= (1 << (self.bits - 1)):
            x -= 1 << self.bits
        return x

    def inr(self, x):
        return self.min <= x <= self.max

    def lit(self, v):
        assert self.inr(v), (self.name, v)
        if self.signed and v == self.min:
            return "%s.MIN" % self.name
        if v == self.max and self.bits >= 32:
            return "%s.MAX" % self.name
        if v < 0:
            return "-%d%s" % (-v, self.name)
        return "%d%s" % (v, self.name)

    def recv(self, v):
        return "(%s)" % self.lit(v)

    def values(self):
        s = {self.min, self.max, 0, 1, 2, 3, self.max // 2, self.max - 1}
        r = math.isqrt(self.max)
        s.update({r, r + 1})
        if self.signed:
            s.update({self.min + 1, -1, -2, -3, self.min // 2, -r, -(r + 1)})
        else:
            s.update({self.max // 2 + 1})
        return sorted(v for v in s if self.inr(v))

    def pair_values(self):
        r = math.isqrt(self.max)
        if self.signed:
            s = {self.min, self.min + 1, -2, -1, 0, 1, 2, r, r + 1, self.max - 1, self.max}
        else:
            s = {0, 1, 2, r, r + 1, self.max // 2 + 1, self.max - 1, self.max}
        return sorted(v for v in s if self.inr(v))

    def pairs(self):
        vals = self.pair_values()
        return [(a, b) for a in vals for b in vals]


TYS = [Ty(*t) for t in TYPES]


def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def trem(a, b):
    return a - b * tdiv(a, b)


class Prog:
    """Accumulates one program: helper fns, per-(family,type) test fns, the main that calls them."""

    def __init__(self, name, std_files, exit_note=""):
        self.name = name
        self.std = std_files
        self.helpers = []
        self.fns = []  # (fn name, body lines, case count)
        self.case = 0
        self.lines = None

    def start(self, fn_name):
        self.lines = []
        self.cur = fn_name
        self.first_case = self.case + 1

    def emit(self, line):
        self.lines.append("    " + line)

    def check(self, cond_fail):
        """cond_fail is an Axiom boolean expression that is true when the case FAILS."""
        self.case += 1
        self.emit("if %s { return %d; }" % (cond_fail, self.case))

    def check_block(self, setup, cond_fail):
        self.case += 1
        self.emit("{ %s if %s { return %d; } }" % (setup, cond_fail, self.case))

    def end(self):
        body = ["fn %s() -> i32 {" % self.cur] + self.lines + ["    0", "}", ""]
        self.fns.append((self.cur, body))
        self.lines = None

    def render(self):
        out = ["// test: helper", "// GENERATED by tests/std/num/gen_tests.py (T454). Do not edit by hand.",
               "// std: " + " ".join(self.std), ""]
        out.extend(self.helpers)
        for _n, body in self.fns:
            out.extend(body)
        out.append("fn main() -> i32 {")
        out.append("    let mut r: i32 = 0;")
        for i, (n, _b) in enumerate(self.fns):
            out.append("    r = %s();" % n)
            out.append("    if r != 0 { return r + %d; }" % ((i + 1) * 100000))
        out.append("    print(\"OK %s\\n\");" % self.name)
        out.append("    0")
        out.append("}")
        out.append("")
        return "\n".join(out)

    def case_count(self):
        return self.case


def opt_helper(t):
    return [
        "fn chk_%s(o: Option<%s>, some: bool, v: %s) -> bool {" % (t.name, t.name, t.name),
        "    match o {",
        "        Option.Some(x) => some && x == v,",
        "        Option.None => !some,",
        "    }",
        "}",
        "",
    ]


def chk_call(t, expr, res):
    if res is None:
        return "!chk_%s(%s, false, 0%s)" % (t.name, expr, t.name)
    return "!chk_%s(%s, true, %s)" % (t.name, expr, t.lit(res))


def bool_lit(b):
    return "true" if b else "false"


