DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"


def to_radix(v, radix):
    if v == 0:
        return "0"
    s = ""
    while v:
        s = DIGITS[v % radix] + s
        v //= radix
    return s


def byte_array(prefix, text, case):
    elems = ", ".join("%d" % ord(c) if False else "b'%s'" % c for c in text)
    return "let %s%d: [%d]u8 = [%s];" % (prefix, case, len(text), elems)


