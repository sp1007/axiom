UNSIGNED_ONLY = """
    // ---- unsigned-only members (AXS-INT-031) -------------------------------------------------
    pub fn is_power_of_two(self: @T@) -> bool {
        self != 0@T@ && (self & (self - 1@T@)) == 0@T@
    }

    pub fn checked_next_power_of_two(self: @T@) -> Option<@T@> {
        if self <= 1@T@ {
            return Option.Some(1@T@);
        }
        let exponent: u32 = @BITS@u32 - (self - 1@T@).leading_zeros();
        if exponent >= @BITS@u32 {
            return Option.None;
        }
        Option.Some(1@T@ << exponent)
    }

    // Panics with "arithmetic overflow" (default checked `*`) when self > 2^(BITS-1).
    pub fn next_power_of_two(self: @T@) -> @T@ {
        if self <= 1@T@ {
            return 1@T@;
        }
        let exponent: u32 = @BITS@u32 - (self - 1@T@).leading_zeros();
        let half: @T@ = 1@T@ << (exponent - 1u32);
        half * 2@T@
    }
"""


def lit(value: int, ty: str) -> str:
    return "%d%s" % (value, ty)


def subst(template: str, mapping: dict) -> str:
    out = template
    for key, value in mapping.items():
        out = out.replace("@%s@" % key, value)
    return out


def num_block(name: str, signed: bool, bits: int, ut: str, st: str) -> str:
    t = name
    nbytes = bits // 8
    g = {}  # guard snippets, each ends with a newline (or is empty)
    if signed:
        g["WRAP_DIV_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return self;\n        }\n" % (t, t))
        g["WRAP_REM_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return 0%s;\n        }\n" % (t, t, t))
        g["SAT_DIV_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return %s.MAX;\n        }\n" % (t, t, t))
        g["CHECKED_ADD_TEST"] = (
            "        if ((self ^ sum) & (rhs ^ sum)) < 0%s {\n            Option.None\n        } else {\n"
            "            Option.Some(sum)\n        }\n" % t)
        g["CHECKED_SUB_BODY"] = (
            "        let diff: %s = self.wrapping_sub(rhs);\n"
            "        if ((self ^ rhs) & (self ^ diff)) < 0%s {\n            Option.None\n        } else {\n"
            "            Option.Some(diff)\n        }\n" % (t, t))
        g["CHECKED_MUL_GUARD"] = (
            "        if (self == -1%s && rhs == %s.MIN) || (rhs == -1%s && self == %s.MIN) {\n"
            "            return Option.None;\n        }\n" % (t, t, t, t))
        g["CHECKED_DIV_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return Option.None;\n        }\n" % (t, t))
        g["CHECKED_NEG_BODY"] = (
            "        if self == %s.MIN {\n            Option.None\n        } else {\n"
            "            Option.Some(-self)\n        }\n" % t)
        g["ADD_FLAG"] = "    ((a ^ sum) & (b ^ sum)) < 0%s\n" % t
        g["SUB_FLAG"] = "    ((a ^ b) & (a ^ diff)) < 0%s\n" % t
        g["OVERFLOWING_DIV_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return pair_%s(%s.MIN, true);\n        }\n" % (t, t, t, t))
        g["OVERFLOWING_REM_GUARD"] = (
            "        if self == %s.MIN && rhs == -1%s {\n            return pair_%s(0%s, true);\n        }\n" % (t, t, t, t))
        g["NEG_OVERFLOW_TEST"] = "self == %s.MIN" % t
    else:
        g["WRAP_DIV_GUARD"] = ""
        g["WRAP_REM_GUARD"] = ""
        g["SAT_DIV_GUARD"] = ""
        g["CHECKED_ADD_TEST"] = (
            "        if sum < self {\n            Option.None\n        } else {\n"
            "            Option.Some(sum)\n        }\n")
        g["CHECKED_SUB_BODY"] = (
            "        if rhs > self {\n            Option.None\n        } else {\n"
            "            Option.Some(self - rhs)\n        }\n")
        g["CHECKED_MUL_GUARD"] = ""
        g["CHECKED_DIV_GUARD"] = ""
        g["CHECKED_NEG_BODY"] = (
            "        if self == 0%s {\n            Option.Some(0%s)\n        } else {\n"
            "            Option.None\n        }\n" % (t, t))
        g["ADD_FLAG"] = "    sum < a\n"
        g["SUB_FLAG"] = "    b > a\n"
        g["OVERFLOWING_DIV_GUARD"] = ""
        g["OVERFLOWING_REM_GUARD"] = ""
        g["NEG_OVERFLOW_TEST"] = "self != 0%s" % t

    def to_items(order):
        lines = []
        for k in order:
            shift = "bits" if k == 0 else "(bits >> %du32)" % (8 * k)
            lines.append("            (%s & 0xFF%s) as u8,\n" % (shift, ut))
        return "".join(lines)

    def from_terms(order):
        # order[i] = index of the byte that carries significance 8*i
        parts = []
        for i, idx in enumerate(order):
            if i == 0:
                parts.append("        (bytes[%d] as %s)" % (idx, ut))
            else:
                parts.append("        ((bytes[%d] as %s) << %du32)" % (idx, ut, 8 * i))
        return " |\n".join(parts)

    le = list(range(nbytes))
    be = list(reversed(le))
    g["TO_LE_ITEMS"] = to_items(le)
    # to_be: element j holds the byte of significance (nbytes-1-j)
    lines = []
    for j in range(nbytes):
        k = nbytes - 1 - j
        shift = "bits" if k == 0 else "(bits >> %du32)" % (8 * k)
        lines.append("            (%s & 0xFF%s) as u8,\n" % (shift, ut))
    g["TO_BE_ITEMS"] = "".join(lines)
    g["FROM_LE_TERMS"] = from_terms(le)
    g["FROM_BE_TERMS"] = from_terms(be)

    mapping = {
        "T": t,
        "UT": ut,
        "BITS": str(bits),
        "MASK": str(bits - 1),
        "BYTES": str(nbytes),
    }
    mapping.update(g)
    body = COMMON
    body += SIGNED_ONLY if signed else UNSIGNED_ONLY
    helpers_text = subst(HELPERS, mapping)
    text = subst(body, mapping)
    return "// ================================================================================================\n" \
           "// %s\n" \
           "// ================================================================================================\n" \
           "%simpl %s {\n%s}\n" % (name, helpers_text, name, text)


def gen_num(only=None) -> str:
    out = [NUM_HEAD]
    for name, signed, bits, ut, st in TYPES:
        if only is not None and name not in only:
            continue
        out.append(num_block(name, signed, bits, ut, st))
        out.append("\n")
    out.append(NUM_TAIL)
    return "".join(out)


