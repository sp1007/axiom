CONVERT_HEAD = """module std.core.convert

""" + BANNER + """//
// Integer conversions (SPEC-40 AXS-INT-042/043).
//
// Surface (all 12 integer types; `bool` is a source of `from`):
//   Dst.from(x)       lossless widening, checked by the compiler: x must be of a type whose every value fits in Dst
//   Dst.try_from(x)   range-checked conversion from any integer type, Result<Dst, TryFromIntError>
//
// Design notes (for the architect)
//   1. `From<T>`/`TryFrom<T>` are generic traits with one impl per source type for the same destination.  The
//      compiler cannot select between several impls of one generic trait for the same Self
//      (`AX_TRAIT_AMBIGUOUS_METHOD`; through a generic bound it silently picks the first impl; see
//      tests/std/num/trait_dispatch_xfail.ax).  Until that works, `from` and `try_from` are inherent generic
//      methods of each integer type whose parameter is bounded by small non-generic helper traits:
//        LosslessToD  "values of Self convert to D without loss"   (one trait per destination D)
//        IntValue     sign and magnitude of any integer value      (read side of try_from)
//      The call syntax of SPEC-40 (`u16.try_from(x)`, `i128.from(x)`) is unchanged and `u32.from(5i64)` is a
//      compile-time error (AX_TRAIT_UNSATISFIED_BOUND), as the spec requires.
//   2. `x.into()` and `x.try_into()` choose the destination from the expected type.  That needs either the
//      generic-trait dispatch above or a static trait method called through a type parameter (`D.f(x)`), which
//      the compiler resolves to the first impl whatever D is (tests/std/num/static_dispatch_xfail.ax).  Neither
//      works yet, so the integer `into`/`try_into` are NOT provided; tests/std/num/into_xfail.test is the
//      executable form of that gap and starts passing (XPASS) when the compiler is fixed.
//   3. The generic traits From/Into/TryFrom/TryInto below are the extension point for non-integer types (a user
//      impl of From<Celsius> for f32, say); they have no integer impls yet.
//   4. i128 and u128 sources work only because trait impl selection knows those two types
//      (prim_kind_matches_name in compiler/traits/solver.ax, fixed by T454).  tests/std/num/convert128.test and
//      int128_generic_dispatch.ax guard it.

use std.core.result.Result
use std.core.cmp.Clone
use std.core.cmp.PartialEq
use std.core.cmp.Eq

// Error of every failed range-checked integer conversion (SPEC-40 AXS-INT-043).  Debug and Display are not
// implemented: std has no such traits yet (follow-up for the formatting library).  `@derive(Copy)` on an empty
// struct is accepted but the verifier still treats a second use as a move (tests/std/num/empty_copy_xfail.ax).
@derive(Copy)
pub struct TryFromIntError {}

impl Clone for TryFromIntError {
    fn clone(self: view<TryFromIntError>) -> TryFromIntError {
        TryFromIntError {}
    }
}

impl PartialEq for TryFromIntError {
    fn eq(self: view<TryFromIntError>, other: view<TryFromIntError>) -> bool {
        true
    }
}

impl Eq for TryFromIntError {}

pub trait From<T> {
    fn from(value: T) -> Self;
}

pub trait Into<T> {
    fn into(self: Self) -> T;
}

pub trait TryFrom<T> {
    type Error;
    fn try_from(value: T) -> Result<Self, Self.Error>;
}

pub trait TryInto<T> {
    type Error;
    fn try_into(self: Self) -> Result<T, Self.Error>;
}

// Sign and magnitude of any integer value: the read side of try_from.
pub trait IntValue {
    fn int_is_negative(self: view<Self>) -> bool;
    fn int_magnitude(self: view<Self>) -> u128;
}

"""

TYPE_NAMES = [t[0] for t in TYPES]
RANGES = {}
for _n, _s, _b, _u, _st in TYPES:
    RANGES[_n] = (-(1 << (_b - 1)), (1 << (_b - 1)) - 1) if _s else (0, (1 << _b) - 1)


def lossless(src: str, dst: str) -> bool:
    """SPEC-40 AXS-INT-042: every value of src is a value of dst (64-bit target)."""
    if src == dst:
        return True
    pair = {("i64", "isize"), ("isize", "i64"), ("u64", "usize"), ("usize", "u64")}
    if (src, dst) in pair:
        return False
    slo, shi = RANGES[src]
    dlo, dhi = RANGES[dst]
    return slo >= dlo and shi <= dhi


def gen_convert() -> str:
    out = [CONVERT_HEAD]

    # IntValue impls
    for name, signed, bits, ut, st in TYPES:
        if signed:
            out.append(
                "impl IntValue for %s {\n"
                "    fn int_is_negative(self: view<%s>) -> bool {\n"
                "        *self < 0%s\n"
                "    }\n"
                "    fn int_magnitude(self: view<%s>) -> u128 {\n"
                "        let value: %s = *self;\n"
                "        if value < 0%s {\n"
                "            (0u128).wrapping_sub(value as u128)\n"
                "        } else {\n"
                "            value as u128\n"
                "        }\n"
                "    }\n"
                "}\n\n" % (name, name, name, name, name, name))
        else:
            out.append(
                "impl IntValue for %s {\n"
                "    fn int_is_negative(self: view<%s>) -> bool {\n"
                "        false\n"
                "    }\n"
                "    fn int_magnitude(self: view<%s>) -> u128 {\n"
                "        (*self) as u128\n"
                "    }\n"
                "}\n\n" % (name, name, name))

    sources = TYPE_NAMES + ["bool"]

    # per-destination helper traits: LosslessToD (implemented by every source that converts to D)
    for dst in TYPE_NAMES:
        trait = "LosslessTo%s" % dst.upper()
        out.append("pub trait %s {\n    fn lossless_to_%s(self: view<Self>) -> %s;\n}\n\n" % (trait, dst, dst))
        for src in sources:
            if src == "bool":
                body = "if *self { 1%s } else { 0%s }" % (dst, dst)
            elif lossless(src, dst):
                body = "(*self) as %s" % dst
            else:
                continue
            out.append(
                "impl %s for %s {\n    fn lossless_to_%s(self: view<%s>) -> %s {\n        %s\n    }\n}\n\n"
                % (trait, src, dst, src, dst, body))

    # inherent API on every integer type
    for name, signed, bits, ut, st in TYPES:
        if signed:
            check = (
                "        if negative {\n"
                "            if magnitude > (%s.MAX as u128) + 1u128 {\n"
                "                return Result.Err(TryFromIntError {});\n"
                "            }\n"
                "            return Result.Ok((magnitude as %s).wrapping_neg());\n"
                "        }\n" % (name, name))
        else:
            check = (
                "        if negative {\n"
                "            return Result.Err(TryFromIntError {});\n"
                "        }\n")
        out.append(
            "impl %s {\n"
            "    pub fn from<S: LosslessTo%s>(value: S) -> %s {\n"
            "        value.lossless_to_%s()\n"
            "    }\n\n"
            "    pub fn try_from<S: IntValue>(value: S) -> Result<%s, TryFromIntError> {\n"
            "        let negative: bool = value.int_is_negative();\n"
            "        let magnitude: u128 = value.int_magnitude();\n"
            "%s"
            "        if magnitude > (%s.MAX as u128) {\n"
            "            return Result.Err(TryFromIntError {});\n"
            "        }\n"
            "        Result.Ok(magnitude as %s)\n"
            "    }\n"
            "}\n\n" % (name, name.upper(), name, name, name, check, name, name))
    return "".join(out).rstrip("\n") + "\n"


def outputs():
    return {
        ROOT / "std" / "core" / "num.ax": gen_num(),
        ROOT / "std" / "core" / "convert.ax": gen_convert(),
    }


def main(argv):
    if "--types" in argv:
        # debugging aid: python gen_num.py --types i8,u8 <out.ax>  writes a reduced num.ax to <out.ax>
        only = argv[argv.index("--types") + 1].split(",")
        Path(argv[argv.index("--types") + 2]).write_bytes(gen_num(only).encode("utf-8"))
        return 0
    check = "--check" in argv
    status = 0
    for path, text in outputs().items():
        data = text.encode("utf-8")
        if check:
            current = path.read_bytes() if path.exists() else b""
            if current != data:
                sys.stderr.write("DIFFERS: %s\n" % path.relative_to(ROOT).as_posix())
                status = 1
        else:
            path.write_bytes(data)
            sys.stdout.write("wrote %s (%d lines)\n" % (path.relative_to(ROOT).as_posix(), text.count("\n")))
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
