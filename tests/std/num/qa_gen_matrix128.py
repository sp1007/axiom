#!/usr/bin/env python3
"""QA generator (T454 round 1): try_from matrix with 128-bit SOURCES x all 12 destinations, exact Python expectations.
Writes tests/std/num/prog/qa_try_from_128_matrix.ax next to this script."""
from pathlib import Path

DST = {"i8": (8, True), "i16": (16, True), "i32": (32, True), "i64": (64, True), "i128": (128, True), "isize": (64, True),
       "u8": (8, False), "u16": (16, False), "u32": (32, False), "u64": (64, False), "u128": (128, False), "usize": (64, False)}
SRC = {"i128": (-2**127, 2**127 - 1), "u128": (0, 2**128 - 1)}
VALUES = [0, 1, 127, 128, 255, 256, 2**15, 2**16, 2**31, 2**32, 2**63 - 1, 2**63, 2**64 - 1, 2**64, 10**20, 2**127 - 1, 2**127,
          2**128 - 1, -1, -128, -129, -2**15 - 1, -2**31, -2**31 - 1, -2**63, -2**63 - 1, -2**127]


def lit(v, ty):
    # `-9223372036854775808i64` panics ("arithmetic overflow") in the interpreter: the literal is negated after it wraps
    # (compiler observation, not std); use the associated constant for the minimum of a signed type.
    if ty in DST and DST[ty][1] and v == -2**(DST[ty][0] - 1):
        return ty + ".MIN"
    return "%d%s" % (v, ty)


def main():
    out = ["// test: helper", "// GENERATED by tests/std/num/qa_gen_matrix128.py (T454 QA round 1). Do not edit by hand.",
           "// std: core/num.ax core/convert.ax", "", "use std.core.result.Result", "use std.core.convert.TryFromIntError", ""]
    for d in DST:
        out += ["fn chk_%s(r: Result<%s, TryFromIntError>, ok: bool, v: %s) -> bool {" % (d, d, d), "    match r {",
                "        Result.Ok(x) => ok && x == v,", "        Result.Err(_) => !ok,", "    }", "}", ""]
    out.append("fn main() -> i32 {")
    n = 0
    for s, (lo, hi) in SRC.items():
        for v in VALUES:
            if not (lo <= v <= hi):
                continue
            for d, (bits, signed) in DST.items():
                dlo, dhi = (-2**(bits - 1), 2**(bits - 1) - 1) if signed else (0, 2**bits - 1)
                ok = dlo <= v <= dhi
                n += 1
                out.append("    if !chk_%s(%s.try_from(%s), %s, %s) { return %d; }" % (
                    d, d, lit(v, s), "true" if ok else "false", lit(v if ok else 0, d), n))
    out += ['    print("OK qa_try_from_128_matrix\\n");', "    0", "}", ""]
    (Path(__file__).parent / "prog" / "qa_try_from_128_matrix.ax").write_text("\n".join(out), newline="\n")
    print(n, "cases")


main()
