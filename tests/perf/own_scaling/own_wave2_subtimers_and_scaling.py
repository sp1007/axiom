#!/usr/bin/env python3
"""T493 perf/correctness guard:
1. Verifies `--time-passes` preserves all 9 top-level `time:` lines unchanged and emits all 9
   `time-own:` sub-timers (`unsafe`, `async`, `mir_build`, `verify_mir`, `own_cap`, `own_init`,
   `verify_own`, `mir_drop`, `own_rest`) immediately after `time: own` with sum matching `time: own`.
2. Stresses intra-procedural `own_cap_check` (compact capability-slot bitset) and `own_check`
   (1-bit definite-ownership bitset + iterative RPO) on a single large function with many locals,
   branches, loops, partial struct moves, and `view`/`mut_view` borrows at N and 4*N blocks:
   verifies `own_cap + own_init` stays fast and scales cleanly without quadratic blow-up.
3. Verifies repeated `-O0` and `-O1` builds with `SOURCE_DATE_EPOCH=0` are byte-identical
   (SPEC-76 INV-DET-004) and the compiled executable prints `OWN_WAVE2_OK`.
"""
import argparse
import hashlib
import os
import re
import statistics
import subprocess
import sys

EXPECTED_TOP = [
    "source", "lex", "parse", "resolve", "hir", "typeck", "own", "mono", "build",
]
EXPECTED_OWN_SUB = [
    "unsafe", "async", "mir_build", "verify_mir",
    "own_cap", "own_init", "verify_own", "mir_drop", "own_rest",
]

TOP_RE = re.compile(r"^time:\s+(\w+)\s+([0-9]+\.[0-9]{4})s$")
OWN_SUB_RE = re.compile(r"^time-own:\s+(\w+)\s+([0-9]+\.[0-9]{4})s$")


def gen_big_fn_program(n_blocks):
    """One large function with `n_blocks` branches + loop + partial moves + views."""
    out = []
    w = out.append
    w("// generated by own_wave2_subtimers_and_scaling.py (T493)")
    w("struct Boxed { a: u64, b: u64 }")
    w("struct Pair { x: Boxed, y: Boxed }")
    w("")
    w("fn read_pair(p: view<Pair>) -> u64 { p.x.a + p.y.b }")
    w("fn bump_pair(p: mut_view<Pair>, d: u64) { p.x.a = p.x.a + d; }")
    w("")
    w("fn big_fn(limit: u64) -> u64 {")
    w("    let mut acc: u64 = 0u64;")
    w("    let mut iter: u64 = 0u64;")
    w("    while iter < limit {")
    for i in range(n_blocks):
        w("        let mut p%d = Pair { x: Boxed { a: iter + %du64, b: %du64 }, y: Boxed { a: 1u64, b: 2u64 } };" % (i, i + 1, i + 2))
        if i % 4 == 0:
            w("        bump_pair(mut_view(p%d), 1u64);" % i)
        if i % 2 == 0:
            w("        let r%d = read_pair(view(p%d));" % (i, i))
            w("        if (r%d & 1u64) == 0u64 {" % i)
            w("            let bx%d = p%d.x;" % (i, i))
            w("            acc = acc + bx%d.a + p%d.y.b;" % (i, i))
            w("        } else {")
            w("            acc = acc + r%d;" % i)
            w("        }")
        else:
            w("        acc = acc + p%d.x.a + p%d.y.b;" % (i, i))
    w("        iter = iter + 1u64;")
    w("    }")
    w("    acc")
    w("}")
    w("")
    w("fn main() -> i32 {")
    w("    let res = big_fn(2u64);")
    w("    if res > 0u64 {")
    w("        print(\"OWN_WAVE2_OK\\n\");")
    w("        0")
    w("    } else {")
    w("        1")
    w("    }")
    w("}")
    w("")
    return "\n".join(out)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for ch in iter(lambda: f.read(1 << 20), b""):
            h.update(ch)
    return h.hexdigest()


def parse_own_timers(txt, expect_full_build):
    top_seen = []
    top_vals = {}
    own_sub_seen = []
    own_sub_vals = {}
    own_idx = -1
    for idx, ln in enumerate(txt.splitlines()):
        s = ln.strip()
        m_top = TOP_RE.match(s)
        if m_top:
            name, val = m_top.group(1), float(m_top.group(2))
            top_seen.append(name)
            top_vals[name] = val
            if name == "own":
                own_idx = idx
            continue
        m_sub = OWN_SUB_RE.match(s)
        if m_sub:
            if own_idx < 0:
                raise RuntimeError("time-own line appeared before `time: own`: %s" % s)
            name, val = m_sub.group(1), float(m_sub.group(2))
            own_sub_seen.append(name)
            own_sub_vals[name] = val
    if expect_full_build and top_seen != EXPECTED_TOP:
        raise RuntimeError("top-level time: stages mismatch: got %r, expected %r" % (top_seen, EXPECTED_TOP))
    if own_sub_seen != EXPECTED_OWN_SUB:
        raise RuntimeError("time-own: sub-timers mismatch: got %r, expected %r" % (own_sub_seen, EXPECTED_OWN_SUB))
    sub_sum = sum(own_sub_vals.values())
    own_t = top_vals["own"]
    if abs(sub_sum - own_t) > 0.05:
        raise RuntimeError("time-own sum %.4fs != time: own %.4fs" % (sub_sum, own_t))
    return top_vals, own_sub_vals


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", required=True)
    ap.add_argument("--tmp", required=True)
    ap.add_argument("--small", type=int, default=40)
    ap.add_argument("--large", type=int, default=160)
    ap.add_argument("--samples", type=int, default=3,
                    help="sequential compiles per size; min of each timer is used (default: 3)")
    ap.add_argument("--limit", type=float, default=2.0,
                    help="max own_cap+own_init seconds at --large (default: 2.0)")
    a = ap.parse_args()
    if a.samples < 1:
        raise ValueError("--samples must be >= 1")
    os.makedirs(a.tmp, exist_ok=True)
    env = dict(os.environ)
    env["SOURCE_DATE_EPOCH"] = "0"

    # 1. Intra-procedural scaling check (`check --time-passes` at small vs large single function)
    own_core = {}
    own_core_med = {}
    for n in (a.small, a.large):
        src = os.path.join(a.tmp, "big_fn_%d.ax" % n)
        with open(src, "w", encoding="utf-8", newline="\n") as f:
            f.write(gen_big_fn_program(n))
        own_samples = []
        cap_samples = []
        init_samples = []
        for _ in range(a.samples):
            p = subprocess.run([os.path.abspath(a.compiler), "check", "--time-passes", src],
                               capture_output=True, env=env, timeout=240)
            txt = (p.stdout + p.stderr).decode("utf-8", "replace")
            if p.returncode != 0:
                raise RuntimeError("check failed on n=%d:\n%s" % (n, txt[-2000:]))
            top_v, sub_v = parse_own_timers(txt, expect_full_build=False)
            own_samples.append(top_v["own"])
            cap_samples.append(sub_v["own_cap"])
            init_samples.append(sub_v["own_init"])
        own_min, own_med = min(own_samples), statistics.median(own_samples)
        cap_min, cap_med = min(cap_samples), statistics.median(cap_samples)
        init_min, init_med = min(init_samples), statistics.median(init_samples)
        own_core[n] = cap_min + init_min
        own_core_med[n] = cap_med + init_med
        sys.stderr.write(
            "n=%d own samples=[%s] min=%.4fs med=%.4fs\n"
            "n=%d own_cap samples=[%s] min=%.4fs med=%.4fs\n"
            "n=%d own_init samples=[%s] min=%.4fs med=%.4fs\n"
            "n=%d own_cap+own_init min=%.4fs (med %.4fs)\n"
            % (
                n, ", ".join("%.4f" % x for x in own_samples), own_min, own_med,
                n, ", ".join("%.4f" % x for x in cap_samples), cap_min, cap_med,
                n, ", ".join("%.4f" % x for x in init_samples), init_min, init_med,
                n, own_core[n], own_core_med[n],
            )
        )

    # With bitset rows, even n=160 (~600 locals, ~300 blocks) completes own_cap + own_init in < 1.0s.
    if own_core[a.large] > a.limit:
        print("FAIL intra-fn own_cap+own_init too slow: %.4fs > %.4fs" % (own_core[a.large], a.limit))
        return 1

    # 2. Full `build --time-passes` sub-timer hygiene & byte-identical determinism at -O0 and -O1
    src_small = os.path.join(a.tmp, "big_fn_%d.ax" % a.small)
    for opt in ("O0", "O1"):
        hashes = []
        for run_idx in (1, 2):
            exe = os.path.join(a.tmp, "big_%s_%d.exe" % (opt, run_idx))
            p = subprocess.run([os.path.abspath(a.compiler), "build", "-" + opt, "--time-passes", src_small, "-o", exe],
                               capture_output=True, env=env, timeout=240)
            txt = (p.stdout + p.stderr).decode("utf-8", "replace")
            if p.returncode != 0:
                raise RuntimeError("build -%s failed:\n%s" % (opt, txt[-2000:]))
            parse_own_timers(txt, expect_full_build=True)
            hashes.append(sha256_file(exe))
            if run_idx == 1:
                r = subprocess.run([exe], capture_output=True, timeout=60)
                if r.returncode != 0 or r.stdout != b"OWN_WAVE2_OK\n":
                    raise RuntimeError("exec -%s failed: rc=%d stdout=%r" % (opt, r.returncode, r.stdout))
        if hashes[0] != hashes[1]:
            print("FAIL determinism (-%s): %s != %s" % (opt, hashes[0], hashes[1]))
            return 1

    sys.stdout.buffer.write(b"OK own_wave2_subtimers_and_scaling\n")
    sys.stdout.buffer.flush()
    return 0


if __name__ == "__main__":
    sys.exit(main())
