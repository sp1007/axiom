#!/usr/bin/env python3
"""T485: the `own` pass (unsafe/concurrency check, MIR build, ownership/init, capability check,
drop elaboration, verifier) must scale linearly with the size of the input file.

Generates the same program shape at N and 4*N units, runs `<compiler> check --time-passes` on both
and requires own(4N) / own(N) <= LIMIT (linear = 4; the default LIMIT 8 absorbs machine noise and the
remaining mildly superlinear parts; HEAD before T485 measured 13.4).
Before T485 the unsafe/concurrency checker rescanned every item of the file for every path and call
expression (quadratic in file size).

usage: own_scaling.py --compiler PATH --tmp DIR [--units N] [--limit X] [--print]
Prints `OK own scaling` on success, `SKIP ...` (exit 0) when a compile exceeds the step timeout,
`FAIL ...` (exit 1) otherwise.
"""

import argparse
import os
import re
import subprocess
import sys
import time


def gen_program(units):
    """A trait, then `units` groups of: structs with a trait impl and an inherent method, a const, an unsafe fn, a safe fn with struct locals, moves,
    views, field accesses, loops, calls to earlier groups and const reads. Valid Axiom, exit 0."""
    out = []
    w = out.append
    w("// generated by tests/perf/own_scaling/own_scaling.py (T485)")
    w("trait Sized2 {")
    w("    fn weight(self: view<Self>) -> u64;")
    w("}")
    w("")
    for i in range(units):
        w("struct Pair%d {" % i)
        w("    a: u64,")
        w("    b: u64,")
        w("}")
        w("")
        w("struct Box%d {" % i)
        w("    p: Pair%d," % i)
        w("    q: Pair%d," % i)
        w("    tag: u32,")
        w("}")
        w("")
        w("const G%d: u64 = %du64;" % (i, i))
        w("")
        w("unsafe fn raw%d(x: u64) -> u64 {" % i)
        w("    x + %du64" % (i % 7))
        w("}")
        w("")
        w("impl Sized2 for Pair%d {" % i)
        w("    fn weight(self: view<Pair%d>) -> u64 {" % i)
        w("        self.a + self.b")
        w("    }")
        w("}")
        w("")
        w("impl Box%d {" % i)
        w("    fn first(self: view<Box%d>) -> u64 {" % i)
        w("        self.p.weight()")
        w("    }")
        w("}")
        w("")
        w("fn sum%d(b: view<Box%d>) -> u64 {" % (i, i))
        w("    b.p.a + b.p.b + b.q.a + b.q.b")
        w("}")
        w("")
        w("fn work%d(n: u64) -> u64 {" % i)
        w("    let mut acc: u64 = G%d;" % i)
        w("    let mut k: u64 = 0u64;")
        w("    while k < n {")
        w("        let bx = Box%d { p: Pair%d { a: k, b: G%d }, q: Pair%d { a: acc %% 1000u64, b: 1u64 }, tag: 3u32 };" % (i, i, i, i))
        w("        let s = sum%d(view(bx)) + bx.first();" % i)
        w("        let moved = bx;")
        w("        let p2 = moved.p;")
        w("        if p2.a > 5u64 {")
        w("            acc = acc + s;")
        w("        } else {")
        w("            acc = acc + unsafe { raw%d(p2.b) };" % i)
        w("        }")
        if i > 0:
            w("        acc = acc + work%d(0u64) + G%d;" % (i - 1, i - 1))
        w("        k = k + 1u64;")
        w("    }")
        w("    acc % 1000000u64")
        w("}")
        w("")
    w("fn main() -> i32 {")
    w("    let r = work%d(2u64);" % (units - 1))
    w("    if r > 0u64 { 0 } else { 0 }")
    w("}")
    w("")
    return "\n".join(out)


PASS_RE = re.compile(r"^time:\s+(\w+)\s+([0-9.]+)\s*s", re.M)


def own_time(compiler, path, timeout):
    t0 = time.time()
    p = subprocess.run([os.path.abspath(compiler), "check", "--time-passes", path], capture_output=True,
                       timeout=timeout)
    text = (p.stdout + p.stderr).decode("utf-8", "replace")
    if p.returncode != 0:
        raise RuntimeError("compiler exit %d on %s:\n%s" % (p.returncode, path, text[-2000:]))
    times = {m.group(1): float(m.group(2)) for m in PASS_RE.finditer(text)}
    if "own" not in times:
        raise RuntimeError("no `own` line in --time-passes output:\n" + text[-2000:])
    return times["own"], time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", required=True)
    ap.add_argument("--tmp", required=True)
    ap.add_argument("--units", type=int, default=300)
    ap.add_argument("--limit", type=float, default=8.0)
    ap.add_argument("--timeout", type=float, default=240.0)
    ap.add_argument("--print", action="store_true", help="print the timings")
    a = ap.parse_args()
    os.makedirs(a.tmp, exist_ok=True)
    res = []
    for n in (a.units, 4 * a.units):
        path = os.path.join(a.tmp, "own_scaling_%d.ax" % n)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(gen_program(n))
        try:
            own, wall = own_time(a.compiler, path, a.timeout)
        except subprocess.TimeoutExpired:
            print("SKIP own scaling: compile of %d units exceeded %ss" % (n, a.timeout))
            return 0
        res.append((n, own, wall))
        if a.print:
            sys.stderr.write("units=%d own=%.3fs wall=%.3fs\n" % (n, own, wall))
    (n1, o1, _), (n4, o4, _) = res
    # Sub-0.05 s timings are noise: compare against a floor so a tiny N cannot fail the ratio.
    ratio = o4 / max(o1, 0.05)
    sys.stderr.write("own(%d)=%.3fs own(%d)=%.3fs ratio %.2f limit %.2f\n" % (n1, o1, n4, o4, ratio, a.limit))
    if ratio > a.limit:
        print("FAIL own scaling: own(%d)=%.3fs own(%d)=%.3fs ratio %.2f > %.2f" % (n1, o1, n4, o4, ratio, a.limit))
        return 1
    print("OK own scaling")
    return 0


if __name__ == "__main__":
    sys.exit(main())
