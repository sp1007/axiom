#!/usr/bin/env python3
"""T494 QA adversarial test:
Stresses every newly-optimized algorithmic path in `frame.ax`, `isel.ax`, and `mir/drop.ax`:
1. High register pressure (>72 simultaneously live locals of mixed sizes: 48 u64 + 16 u32 + 8 u8)
   in a single function with nested loops, helper calls, division/modulo (RAX/RDX clobbers),
   and variable shifts (RCX clobber). Exercises:
   - `liveness_solve_dataflow_csr` multi-word bitset path (`words_per_bb >= 2`) + dirty worklist
   - `x64_regalloc_with_pgo_in_arena` O(N) counting sort (`vreg_count > 32`) AND small-fn insertion
     sort (`vreg_count <= 32`)
   - O(1)-amortized backward physical-register interference tracking (`bit_last_step`, `enter_step`,
     `call_last_step`)
   - colored spill-slot reuse with mixed sizes/alignments (`u64`, `u32`, `u8`)
2. Deep conditional drops, multi-level nested drop expansion (struct -> array -> struct -> Drop),
   interleaved non-drop basic blocks (`drop_block_needs_rewrite == false` fast-skip), and
   `DropNeedsCache` hits across multiple drop and non-drop types/functions.
3. Verifies exact native runtime results against an independent Python reference model AND
   repeated-build byte determinism (INV-DET-004) at both `-O0` and `-O1`.
"""
import argparse
import hashlib
import os
import subprocess
import sys

MASK64 = (1 << 64) - 1


def u64(x):
    return x & MASK64


def u32(x):
    return x & 0xFFFFFFFF


def u8(x):
    return x & 0xFF


def ref_mix_call(a, b, c, d):
    return u64(((u64(a * 3) ^ u64(b * 5)) + u64(c * 7) + d) % 1000003)


def ref_small_fn(v):
    a = u64(v + 11)
    b = u64(a * 3)
    c = u64(b ^ 0x5A)
    return u64(a + b + c)


def ref_high_pressure_regalloc(seed):
    xs = [u64(seed + i * 7 + 1) for i in range(48)]
    ys = [u32(seed + i * 11 + 3) for i in range(16)]
    zs = [u8(seed + i * 13 + 5) for i in range(8)]
    acc = u64(seed)
    for i in range(3):
        for j in range(2):
            sh = (i + j + 1) & 3
            a = u64((xs[i] + xs[16 + j] + xs[32 + i + j]) << sh)
            b = u64(ys[i * 2 + j] + ys[8 + i + j])
            c = u64(zs[i + j] + zs[4 + j])
            q = u64((acc + a + 19) // 7)
            r = u64((acc + b + 23) % 13)
            m = ref_mix_call(a, b, c, u64(q + r))
            acc = u64(acc + m + ref_small_fn(u64(i + j)))
    # Fold every single one of the 72 live locals after the loop so all remain live across calls/loops.
    for i, x in enumerate(xs):
        acc = u64(acc + u64(x * (i + 1)))
    for i, y in enumerate(ys):
        acc = u64(acc + u64(y) * (i + 3))
    for i, z in enumerate(zs):
        acc = u64(acc + u64(z) * (i + 5))
    return acc


def ref_drop_hash():
    """Simulates the exact Axiom drop sequence of `deep_conditional_drops` for modes 0..3."""
    h = 1

    def record(tag):
        nonlocal h
        h = (h * 131 + tag) % 1000000007

    for mode in range(4):
        # Local declarations in order:
        #   a: DropLeaf(10 + mode)
        #   hld: DropHolder(tag=20+mode, inner=DropLeaf(30+mode))
        #   arr: DropArrayWrap([40+mode, 41+mode, 42+mode])
        #   b: DropLeaf(50 + mode)
        a_live = True
        hld_live = True
        arr_live = True
        b_live = True

        # Non-drop basic block chain computes pure scalar work (no flagged locals touched).
        if mode == 0:
            # Consume `a` inside branch; `a` drops inside `consume_leaf` immediately.
            record(10 + mode)
            a_live = False
        elif mode == 1:
            # Early return: active locals drop in reverse declaration order (b, arr, hld, a).
            record(50 + mode)
            record(40 + mode)
            record(41 + mode)
            record(42 + mode)
            record(20 + mode)
            record(30 + mode)
            record(10 + mode)
            continue
        elif mode == 2:
            # Consume `b` and keep `a`, `hld`, `arr`.
            record(50 + mode)
            b_live = False
        else:
            # Consume `hld` inside branch: DropHolder::drop then inner DropLeaf::drop.
            record(20 + mode)
            record(30 + mode)
            hld_live = False

        # Function exit drops remaining locals in reverse declaration order: b, arr, hld, a.
        if b_live:
            record(50 + mode)
        if arr_live:
            record(40 + mode)
            record(41 + mode)
            record(42 + mode)
        if hld_live:
            record(20 + mode)
            record(30 + mode)
        if a_live:
            record(10 + mode)
    return h


def gen_program():
    exp_reg = ref_high_pressure_regalloc(42)
    exp_drop = ref_drop_hash()
    out = []
    w = out.append
