def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for ch in iter(lambda: f.read(1 << 20), b""):
            h.update(ch)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", required=True)
    ap.add_argument("--tmp", required=True)
    a = ap.parse_args()
    os.makedirs(a.tmp, exist_ok=True)
    src = os.path.join(a.tmp, "t494_adversarial.ax")
    with open(src, "w", encoding="utf-8", newline="\n") as f:
        f.write(gen_program())

    env = dict(os.environ)
    env["SOURCE_DATE_EPOCH"] = "0"

    for opt in ("O0", "O1"):
        exe1 = os.path.join(a.tmp, "adv_%s_1.exe" % opt)
        exe2 = os.path.join(a.tmp, "adv_%s_2.exe" % opt)
        hashes = []
        for exe in (exe1, exe2):
            cmd = [os.path.abspath(a.compiler), "build", src, "-o", exe, "-" + opt]
            p = subprocess.run(cmd, capture_output=True, env=env, timeout=300)
            if p.returncode != 0:
                txt = (p.stdout + p.stderr).decode("utf-8", "replace")
                print("FAIL build (-%s, rc=%d):\n%s" % (opt, p.returncode, txt[-2000:]))
                return 1
            hashes.append(sha256_file(exe))
        if hashes[0] != hashes[1]:
            print("FAIL determinism (-%s): %s != %s" % (opt, hashes[0], hashes[1]))
            return 1
        for exe in (exe1, exe2):
            r = subprocess.run([exe], capture_output=True, timeout=60)
            out = r.stdout.decode("utf-8", "replace")
            if r.returncode != 0 or out != "REGALLOC_DROP_OK\n":
                print("FAIL native exec (%s, -%s): rc=%d stdout=%r" % (exe, opt, r.returncode, out))
                return 1

    sys.stdout.buffer.write(b"OK qa_t494_regalloc_drop_adversarial\n")
    sys.stdout.buffer.flush()
    return 0


if __name__ == "__main__":
    sys.exit(main())
