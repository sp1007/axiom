#!/usr/bin/env python3
"""T486: the `build` phase (MIR build, drop elaboration, MIR opt, LIR lowering, ABI lowering, isel,
frame/regalloc, machine-IR verify, encode, object model, PE link) must scale linearly with the size of
the input file.

Generates the same program shape at N and 4*N units, runs `<compiler> build --time-passes` on both
(`--samples 3` sequential compiles per size, taking the minimum of each timer to reject host-load
jitter while also printing the median and all samples on stderr) and requires
build(4N) / build(N) <= LIMIT (linear = 4; the default LIMIT 5 absorbs machine noise).
Before T486 several parts of the build phase did a whole-program scan per call site / per symbol
reference (symbol-name lookup over all HIR items per call, object symbol lookup by linear search per
`lea`, linker global lookup by linear search, ...), i.e. quadratic in the file size.

usage: build_scaling.py --compiler PATH --tmp DIR [--units N] [--limit X] [--samples K] [--opt O0|O1] [--print]
Prints `OK build scaling` on success, `SKIP ...` (exit 0) when a compile exceeds the step timeout,
`FAIL ...` (exit 1) otherwise. The produced executables are run and must exit 0.
"""

import argparse
import os
import re
import statistics
import subprocess
import sys
import time


def gen_program(units):
    """`units` groups of: structs with a trait impl and an inherent method, a const, a const table, a
    string literal, a fn with struct locals, loops, calls to earlier groups. Valid Axiom, exit 0."""
    out = []
    w = out.append
    w("// generated by tests/perf/build_scaling/build_scaling.py (T486)")
    w("trait Weigh {")
    w("    fn weight(self: view<Self>) -> u64;")
    w("}")
    w("")
    for i in range(units):
        w("struct Pair%d {" % i)
        w("    a: u64,")
        w("    b: u64,")
        w("}")
        w("")
        w("struct Box%d {" % i)
        w("    p: Pair%d," % i)
        w("    q: Pair%d," % i)
        w("    tag: u32,")
        w("}")
        w("")
        w("const G%d: u64 = %du64;" % (i, i))
        w("const T%d: [4]u64 = [%du64, %du64, %du64, %du64];" % (i, i, i + 1, i + 2, i + 3))
        w("")
        w("impl Weigh for Pair%d {" % i)
        w("    fn weight(self: view<Pair%d>) -> u64 {" % i)
        w("        self.a + self.b")
        w("    }")
        w("}")
        w("")
        w("impl Box%d {" % i)
        w("    fn first(self: view<Box%d>) -> u64 {" % i)
        w("        self.p.weight()")
        w("    }")
        w("}")
        w("")
        w("fn sum%d(b: view<Box%d>) -> u64 {" % (i, i))
        w("    b.p.a + b.p.b + b.q.a + b.q.b")
        w("}")
        w("")
        w("fn label%d() -> usize {" % i)
        w("    let s = \"label number %d\";" % i)
        w("    len(s)")
        w("}")
        w("")
        w("fn work%d(n: u64) -> u64 {" % i)
        w("    let mut acc: u64 = G%d + T%d[(n %% 4u64) as usize];" % (i, i))
        w("    let mut k: u64 = 0u64;")
        w("    while k < n {")
        w("        let bx = Box%d { p: Pair%d { a: k, b: G%d }, q: Pair%d { a: acc %% 1000u64, b: 1u64 }, tag: 3u32 };" % (i, i, i, i))
        w("        let s = sum%d(view(bx)) + bx.first() + (label%d() as u64);" % (i, i))
        w("        if s > 5u64 {")
        w("            acc = acc + s;")
        w("        } else {")
        w("            acc = acc + 1u64;")
        w("        }")
        if i > 0:
            w("        acc = acc + work%d(0u64) + G%d;" % (i - 1, i - 1))
        w("        k = k + 1u64;")
        w("    }")
        w("    acc % 1000000u64")
        w("}")
        w("")
    w("fn main() -> i32 {")
    w("    let r = work%d(2u64);" % (units - 1))
    w("    if r > 0u64 { 0 } else { 1 }")
    w("}")
    w("")
    return "\n".join(out)


PASS_RE = re.compile(r"^time:\s+(\w+)\s+([0-9.]+)\s*s", re.M)
SUB_RE = re.compile(r"^time-build:\s+(\w+)\s+([0-9.]+)\s*s", re.M)


def build_time(compiler, path, exe, opt, timeout):
    t0 = time.time()
    cmd = [os.path.abspath(compiler), "build", "--time-passes", path, "-o", exe]
    if opt == "O1":
        cmd.append("-O1")
    p = subprocess.run(cmd, capture_output=True, timeout=timeout)
    text = (p.stdout + p.stderr).decode("utf-8", "replace")
    if p.returncode != 0:
        raise RuntimeError("compiler exit %d on %s:\n%s" % (p.returncode, path, text[-2000:]))
    times = {m.group(1): float(m.group(2)) for m in PASS_RE.finditer(text)}
    subs = {m.group(1): float(m.group(2)) for m in SUB_RE.finditer(text)}
    if "build" not in times:
        raise RuntimeError("no `build` line in --time-passes output:\n" + text[-2000:])
    r = subprocess.run([exe], capture_output=True, timeout=60)
    if r.returncode != 0:
        raise RuntimeError("%s exited %d" % (exe, r.returncode))
    return times["build"], subs, time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--compiler", required=True)
    ap.add_argument("--tmp", required=True)
    ap.add_argument("--units", type=int, default=150)
    ap.add_argument("--limit", type=float, default=5.0)
    ap.add_argument("--frame-limit", type=float, default=None,
                    help="max frame(4N) / max(frame(N), 0.05) ratio when time-build sub-timers are present")
    ap.add_argument("--frame-to-ir-limit", type=float, default=None,
                    help="max frame(4N) / max(mir_build(4N)+lir(4N), 0.05) ratio (CPU-speed-independent budget)")
    ap.add_argument("--hot-to-ir-limit", type=float, default=None,
                    help="max (frame(4N)+isel(4N)) / max(mir_build(4N)+lir(4N), 0.05) ratio")
    ap.add_argument("--build-budget", type=float, default=None,
                    help="optional absolute upper bound on build(4N) in seconds")
    ap.add_argument("--opt", default="O0", choices=["O0", "O1"])
    ap.add_argument("--samples", type=int, default=3,
                    help="sequential compiles per size; min of each timer is used (default: 3)")
    ap.add_argument("--timeout", type=float, default=300.0)
    ap.add_argument("--print", action="store_true", help="print the timings")
    a = ap.parse_args()
    if a.samples < 1:
        raise ValueError("--samples must be >= 1")
    os.makedirs(a.tmp, exist_ok=True)
    res = []
    for n in (a.units, 4 * a.units):
        path = os.path.join(a.tmp, "build_scaling_%d.ax" % n)
        exe = os.path.join(a.tmp, "build_scaling_%d.exe" % n)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(gen_program(n))
        bt_samples = []
        wall_samples = []
        sub_samples = {}
        for _ in range(a.samples):
            try:
                bt, subs, wall = build_time(a.compiler, path, exe, a.opt, a.timeout)
            except subprocess.TimeoutExpired:
                print("SKIP build scaling: compile of %d units exceeded %ss" % (n, a.timeout))
                return 0
            bt_samples.append(bt)
            wall_samples.append(wall)
            for k, v in subs.items():
                sub_samples.setdefault(k, []).append(v)
        bt_min = min(bt_samples)
        bt_med = statistics.median(bt_samples)
        subs_min = {k: min(vs) for k, vs in sub_samples.items()}
        subs_med = {k: statistics.median(vs) for k, vs in sub_samples.items()}
        wall_total = sum(wall_samples)
        sys.stderr.write(
            "units=%d build samples=[%s] min=%.3fs med=%.3fs wall_total=%.3fs\n"
            % (n, ", ".join("%.3f" % x for x in bt_samples), bt_min, bt_med, wall_total)
        )
        for key in ("frame", "isel", "mir_build", "lir", "mir_drop"):
            if key in sub_samples:
                vs = sub_samples[key]
                sys.stderr.write(
                    "units=%d %s samples=[%s] min=%.3fs med=%.3fs\n"
                    % (n, key, ", ".join("%.3f" % x for x in vs), subs_min[key], subs_med[key])
                )
        res.append((n, bt_min, bt_med, subs_min, subs_med, wall_total))
    (n1, b1, b1_med, s1, s1_med, _), (n4, b4, b4_med, s4, s4_med, _) = res
    # Sub-0.05 s timings are noise: compare against a floor so a tiny N cannot fail the ratio.
    ratio = b4 / max(b1, 0.05)
    med_ratio = b4_med / max(b1_med, 0.05)
    sys.stderr.write(
        "build(%d)=min %.3fs (med %.3fs) build(%d)=min %.3fs (med %.3fs) ratio %.2f (med %.2f) limit %.2f\n"
        % (n1, b1, b1_med, n4, b4, b4_med, ratio, med_ratio, a.limit)
    )
    if ratio > a.limit:
        print("FAIL build scaling: build(%d)=%.3fs build(%d)=%.3fs ratio %.2f > %.2f" % (n1, b1, n4, b4, ratio, a.limit))
        return 1
    if a.build_budget is not None and b4 > a.build_budget:
        print("FAIL build scaling: build(%d)=%.3fs > budget %.3fs" % (n4, b4, a.build_budget))
        return 1
    if "frame" in s1 and "frame" in s4:
        f1, f4 = s1["frame"], s4["frame"]
        f1_med, f4_med = s1_med["frame"], s4_med["frame"]
        fratio = f4 / max(f1, 0.05)
        f_med_ratio = f4_med / max(f1_med, 0.05)
        ir4 = s4.get("mir_build", 0.0) + s4.get("lir", 0.0)
        ir4_med = s4_med.get("mir_build", 0.0) + s4_med.get("lir", 0.0)
        f_to_ir = f4 / max(ir4, 0.05)
        f_to_ir_med = f4_med / max(ir4_med, 0.05)
        hot4 = f4 + s4.get("isel", 0.0)
        hot4_med = f4_med + s4_med.get("isel", 0.0)
        hot_to_ir = hot4 / max(ir4, 0.05)
        hot_to_ir_med = hot4_med / max(ir4_med, 0.05)
        sys.stderr.write(
            "frame(%d)=min %.3fs (med %.3fs) frame(%d)=min %.3fs (med %.3fs) ratio %.2f (med %.2f) "
            "frame/ir=%.2f (med %.2f) (frame+isel)/ir=%.2f (med %.2f)\n"
            % (n1, f1, f1_med, n4, f4, f4_med, fratio, f_med_ratio, f_to_ir, f_to_ir_med, hot_to_ir, hot_to_ir_med)
        )
        if a.frame_limit is not None and fratio > a.frame_limit:
            print("FAIL build scaling: frame(%d)=%.3fs frame(%d)=%.3fs ratio %.2f > %.2f"
                  % (n1, f1, n4, f4, fratio, a.frame_limit))
            return 1
        if a.frame_to_ir_limit is not None and f_to_ir > a.frame_to_ir_limit:
            print("FAIL build scaling: frame(%d)=%.3fs / (mir_build+lir)=%.3fs = %.2f > %.2f"
                  % (n4, f4, ir4, f_to_ir, a.frame_to_ir_limit))
            return 1
        if a.hot_to_ir_limit is not None and hot_to_ir > a.hot_to_ir_limit:
            print("FAIL build scaling: (frame+isel)(%d)=%.3fs / (mir_build+lir)=%.3fs = %.2f > %.2f"
                  % (n4, hot4, ir4, hot_to_ir, a.hot_to_ir_limit))
            return 1
    print("OK build scaling")
    return 0


if __name__ == "__main__":
    sys.exit(main())
