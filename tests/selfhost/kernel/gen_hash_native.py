#!/usr/bin/env python3
"""Generator of the hash bundles (T134, ADR-0034 s1/s3, audit OI-03).

It writes two test programs that embed a real Axiom hash module VERBATIM and check it against the
independent Python reference vectors (tests/unit/kernel/hash_vectors.txt, produced by
tests/unit/kernel/gen_hash_vectors.py - an implementation independent of both compilers):

  tests/selfhost/kernel/hash_native.ax   compiler/kernel/hash.ax   (the module axiomc is built from)
  tests/std/core/qa_hash_vectors.ax      std/core/hash.ax           (the std hash)

Both run in the interpreter and natively (`modes: interp native`). The extra expected values (typed writers,
combine) are computed here with the same reference implementation, never with axiom0's C kernel/hash.c.

    python tests/selfhost/kernel/gen_hash_native.py           # rewrite both files
    python tests/selfhost/kernel/gen_hash_native.py --check   # exit 1 if either file differs
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))


def load_reference():
    path = os.path.join(ROOT, "tests", "unit", "kernel", "gen_hash_vectors.py")
    spec = importlib.util.spec_from_file_location("gen_hash_vectors", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


REF = load_reference()


def read_vectors():
    """(expected hash, key bytes) for every line of hash_vectors.txt, cross-checked with the reference."""
    out = []
    path = os.path.join(ROOT, "tests", "unit", "kernel", "hash_vectors.txt")
    with open(path, "r", encoding="utf-8", newline="") as f:
        for line in f.read().split("\n"):
            if not line or line.startswith("#"):
                continue
            h, kind, data = line.split(" ", 2)
            if kind == "hex":
                key = b"" if data == "-" else bytes.fromhex(data)
            elif kind == "text":
                key = data.encode("utf-8")
            elif kind == "seq":
                key = REF.seq(int(data))
            else:
                raise SystemExit("unknown vector kind " + kind)
            assert REF.axh64(key) == int(h, 16), "hash_vectors.txt disagrees with the reference for " + line
            out.append((int(h, 16), key))
    return out


def chunks(items, per_line):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


def tables(vectors):
    keys = bytearray()
    offs, lens, hashes = [], [], []
    for h, key in vectors:
        offs.append(len(keys))
        lens.append(len(key))
        keys += key
        hashes.append(h)
    keys.append(0)  # padding byte: the offset of an empty key at the end stays a valid index
    t = []
    t.append("const KEYS: [%d]u8 = [\n%s\n];" % (len(keys), chunks(["%du8" % b for b in keys], 24)))
    t.append("const OFFS: [%d]usize = [\n%s\n];" % (len(offs), chunks(["%d" % o for o in offs], 16)))
    t.append("const LENS: [%d]usize = [\n%s\n];" % (len(lens), chunks(["%d" % n for n in lens], 16)))
    t.append("const HASHES: [%d]u64 = [\n%s\n];" % (len(hashes), chunks(["0x%016xu64" % h for h in hashes], 4)))
    return "\n\n".join(t), len(vectors), len(keys)


def le(v, n):
    return v.to_bytes(n, "little")


def header(test_stdout, source_rel, title):
    return (
        "// test: run\n"
        "// modes: interp native\n"
        "// timeout: 120\n"
        "// stdout: %s\\n\n"
        "// GENERATED by tests/selfhost/kernel/gen_hash_native.py - do not edit by hand.\n"
        "// %s: %s is embedded verbatim below; the vectors come from tests/unit/kernel/hash_vectors.txt\n"
        "// (independent Python reference), the typed-writer values are computed by the same reference.\n"
        % (test_stdout, title, source_rel)
    )


def kernel_bundle(vectors):
    src = open(os.path.join(ROOT, "compiler", "kernel", "hash.ax"), "r", encoding="utf-8", newline="").read()
    tbl, m, nkeys = tables(vectors)
    u32_v, u64_v = 0x04030201, 0x0807060504030201
    c_a, c_b = 100, 200
    exp = {
        "u32": REF.axh64(le(u32_v, 4)),
        "u64": REF.axh64(le(u64_v, 8)),
        "u64_zero": REF.axh64(le(0, 8)),
        "combine": REF.axh64(le(c_a, 8) + le(c_b, 8)),
    }
    body = """
@intrinsic unsafe fn address_of<T>(val: T) -> *const T { 0 as *const T }

%(tbl)s

fn main() -> i32 {
    // view() of a const table is rejected by the capability check, so the keys are copied to a local array
    let keys: [%(nkeys)d]u8 = KEYS;
    let mut i: usize = 0;
    while i < %(m)d {
        let off = OFFS[i];
        let n = LENS[i];
        let p = unsafe { address_of(keys[off]) };
        // one call over the whole key
        if ax_hash_bytes(p, n) != HASHES[i] { return (i + 1) as i32; }
        // the same key written in two parts, split at every position (short keys only)
        let mut k: usize = 0;
        while n <= 40 && k <= n {
            let mut s = ax_hasher_new();
            ax_hasher_write(mut_view(s), p, k);
            ax_hasher_write(mut_view(s), unsafe { p + k }, n - k);
            if ax_hasher_finish(view(s)) != HASHES[i] { return (100 + i) as i32; }
            k = k + 1;
        }
        i = i + 1;
    }
    // typed writers and combine against the Python reference (little-endian bytes)
    if ax_hash_u32(0x04030201u32) != 0x%(u32)016xu64 { return 201; }
    if ax_hash_u64(0x0807060504030201u64) != 0x%(u64)016xu64 { return 202; }
    if ax_hash_u64(0u64) != 0x%(u64z)016xu64 { return 203; }
    if ax_hash_combine(100u64, 200u64) != 0x%(comb)016xu64 { return 204; }
    print("AXH64 KERNEL HASH PASS\\n");
    0
}
""" % {"tbl": tbl, "nkeys": nkeys, "m": m, "u32": exp["u32"], "u64": exp["u64"], "u64z": exp["u64_zero"], "comb": exp["combine"]}
    return header("AXH64 KERNEL HASH PASS", "compiler/kernel/hash.ax", "kernel hash bundle") + "\n" + src.rstrip("\n") + "\n" + body


def std_bundle(vectors):
    src = open(os.path.join(ROOT, "std", "core", "hash.ax"), "r", encoding="utf-8", newline="").read()
    tbl, m, nkeys = tables(vectors)
    typed = [
        ("write_u8(0x07u8)", le(7, 1)),
        ("write_u16(0x0201u16)", le(0x0201, 2)),
        ("write_u32(0x04030201u32)", le(0x04030201, 4)),
        ("write_u64(0x0807060504030201u64)", le(0x0807060504030201, 8)),
        ("write_i32(-1i32)", le(0xFFFFFFFF, 4)),
        ("write_usize(7usize)", le(7, 8)),
    ]
    checks = []
    for n, (call, data) in enumerate(typed):
        checks.append("    let mut t%d = Axh64Hasher.new();\n    t%d.%s;\n    if t%d.finish() != 0x%016xu64 { return %d; }"
                      % (n, n, call, n, REF.axh64(data), 201 + n))
    body = """
%(tbl)s

fn main() -> i32 {
    // view() of a const table is rejected by the capability check, so the keys are copied to a local array
    let keys: [%(nkeys)d]u8 = KEYS;
    let all: view<[u8]> = view(keys);
    let mut i: usize = 0;
    while i < %(m)d {
        let off = OFFS[i];
        let n = LENS[i];
        let whole = all[off..off + n];
        if hash64(whole) != HASHES[i] { return (i + 1) as i32; }
        // the same key written in two parts, split at every position (short keys only)
        let mut k: usize = 0;
        while n <= 40 && k <= n {
            let first = all[off..off + k];
            let second = all[off + k..off + n];
            let mut h = Axh64Hasher.new();
            h.write(first);
            h.write(second);
            if h.finish() != HASHES[i] { return (100 + i) as i32; }
            k = k + 1;
        }
        i = i + 1;
    }
    // typed writers against the Python reference (little-endian bytes)
%(checks)s
    print("AXH64 VECTORS PASS\\n");
    0
}
""" % {"tbl": tbl, "nkeys": nkeys, "m": m, "checks": "\n".join(checks)}
    return header("AXH64 VECTORS PASS", "std/core/hash.ax", "std hash bundle") + "\n" + src.rstrip("\n") + "\n" + body


def outputs():
    vectors = read_vectors()
    return [
        (os.path.join(HERE, "hash_native.ax"), kernel_bundle(vectors)),
        (os.path.join(ROOT, "tests", "std", "core", "qa_hash_vectors.ax"), std_bundle(vectors)),
    ]


def main():
    outs = outputs()
    if "--check" in sys.argv[1:]:
        ok = True
        for path, text in outs:
            with open(path, "r", encoding="utf-8", newline="") as f:
                same = f.read() == text
            ok = ok and same
            print("%s %s" % (os.path.relpath(path, ROOT).replace("\\", "/"), "up to date" if same else "DIFFERS"))
        return 0 if ok else 1
    for path, text in outs:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
