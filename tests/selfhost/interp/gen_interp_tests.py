#!/usr/bin/env python3
"""Bundler for selfhost MIR interpreter unit and differential tests (T083a).

Combines the compiler data model and MIR modules with compiler/interp/*
plus each test harness main module into standalone selfhost test files in
tests/selfhost/interp/.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tests", "selfhost"))

import bundle_common as bc  # noqa: E402

UNIT_MODULES = [
    ("compiler.kernel.id", "compiler"),
    ("compiler.kernel.hash", "compiler"),
    ("compiler.kernel.arena", "compiler"),
    ("compiler.kernel.interner", "compiler"),
    ("compiler.source.span", "compiler"),
    ("compiler.source.manager", "compiler"),
    ("compiler.diag.code", "compiler"),
    ("compiler.diag.emitter", "compiler"),
    ("compiler.diag.format", "compiler"),
    ("compiler.lex.token", "compiler"),
    ("compiler.syntax.ast", "compiler"),
    ("compiler.resolve.symtab", "compiler"),
    ("compiler.hir.hir", "compiler"),
    ("compiler.types.types", "compiler"),
    ("compiler.types.layout", "compiler"),
    ("compiler.traits.solver", "compiler"),
    ("compiler.traits.mono", "compiler"),
    ("compiler.mir.mir", "compiler"),
    ("compiler.mir.drop", "compiler"),
    ("compiler.mir.builder", "compiler"),
    ("compiler.mir", "compiler"),
    ("compiler.interp.value", "compiler"),
    ("compiler.interp.oracle", "compiler"),
    ("compiler.interp.frame", "compiler"),
    ("compiler.interp.interp", "compiler"),
    ("compiler.interp", "compiler"),
]


def bundle_one(in_name, out_name, stdout_line, prelude_text, modules_text):
    in_path = os.path.join(HERE, in_name)
    main_src = bc.read_bytes(in_path).decode("utf-8").replace("\r\n", "\n")
    main_src = main_src.replace("use std.core.host.", "use host_intrinsics.")
    header = (
        "// test: run\n"
        "// timeout: 600\n"
        "// stdout: %s\\n\n"
        "// Generated by tests/selfhost/interp/gen_interp_tests.py; do not edit directly.\n\n"
    ) % stdout_line
    text = header + prelude_text + "\n" + modules_text + "\n" + main_src
    out_path = os.path.join(HERE, out_name)
    return out_path, text


def main():
    check_mode = "--check" in sys.argv[1:] or "check" in sys.argv[1:]
    prelude_text = bc.build_prelude_text(include_sym_pad=True, sym_pad_count=800, include_std_sys=True, root=ROOT)
    modules_text = bc.assemble_compiler_modules(UNIT_MODULES, root=ROOT)
    outs = [
        bundle_one("unit_main.ax.in", "qa_interp_unit.ax", "ALL INTERP UNIT TESTS PASSED", prelude_text, modules_text),
        bundle_one("exec_a_main.ax.in", "qa_interp_exec_a.ax", "ALL INTERP EXEC A TESTS PASSED", prelude_text, modules_text),
        bundle_one("exec_b_main.ax.in", "qa_interp_exec_b.ax", "ALL INTERP EXEC B TESTS PASSED", prelude_text, modules_text),
    ]
    return bc.write_or_check_bundles(outs, check_mode, root=ROOT)


if __name__ == "__main__":
    sys.exit(main())
