def _make_non_aborting_member(main_src, stdout_line):
    """Converts `qa_check` from aborting `assert(false)` into a failure counter so merged siblings still run."""
    qa_def = "fn qa_check(cond: bool) {\n    if !cond {\n        assert(false);\n    }\n}"
    if qa_def not in main_src:
        raise ValueError("expected qa_check definition not found")
    # Replace qa_check(...) calls before replacing its definition
    main_src = main_src.replace(
        qa_def,
        "fn __qa_check_cnt(failed: mut_view<i32>, cond: bool) {\n"
        "    if !cond {\n"
        "        *failed = *failed + 1;\n"
        "    }\n"
        "}",
        1,
    )
    main_src = main_src.replace("qa_check(", "__qa_check_cnt(mut_view(*__qa_fail), ")

    # Identify all test_*() functions called inside pub fn main() (after replacements so offsets match)
    m_main = re.search(r"^pub fn main\(\) -> i32 \{(.*)\}\s*$", main_src, re.S | re.M)
    if not m_main:
        raise ValueError("expected pub fn main() -> i32 not found")
    test_fns = re.findall(r"\b(test_[A-Za-z0-9_]+)\(\);", m_main.group(1))
    if not test_fns:
        raise ValueError("no test_*() calls found in main()")

    prefix = main_src[:m_main.start()]
    for fn_name in test_fns:
        pat = "fn %s() {" % fn_name
        if pat not in prefix:
            raise ValueError("expected %s not found" % pat)
        prefix = prefix.replace(pat, "fn %s(__qa_fail: mut_view<i32>) {" % fn_name, 1)

    new_calls = "\n".join("    %s(mut_view(__qa_fail));" % fn_name for fn_name in test_fns)
    new_main = (
        "pub fn main() -> i32 {\n"
        "    let mut __qa_fail: i32 = 0;\n"
        "%s\n"
        "    if __qa_fail != 0 {\n"
        "        return __qa_fail;\n"
        "    }\n"
        "    print(\"%s\\n\");\n"
        "    0\n"
        "}\n"
    ) % (new_calls, stdout_line)
    return prefix + new_main


def load_member(in_name, orig_out_name, stdout_line):
    in_path = os.path.join(HERE, in_name)
    main_src = bc.read_bytes(in_path).decode("utf-8").replace("\r\n", "\n")
    main_src = main_src.replace("use std.core.host.", "use host_intrinsics.")
    main_src = _make_non_aborting_member(main_src, stdout_line)
    hdrs = [
        "// test: run",
        "// timeout: 600",
        "// stdout: %s\\n" % stdout_line,
    ]
    return orig_out_name, hdrs, main_src


def main():
    check_mode = "--check" in sys.argv[1:] or "check" in sys.argv[1:]
    prelude_text = bc.build_prelude_text(include_sym_pad=True, sym_pad_count=800, include_std_sys=True, root=ROOT)
    modules_text = bc.assemble_compiler_modules(UNIT_MODULES, root=ROOT)
    members = [
        load_member("unit_main.ax.in", "qa_interp_unit.ax", "ALL INTERP UNIT TESTS PASSED"),
        load_member("exec_a_main.ax.in", "qa_interp_exec_a.ax", "ALL INTERP EXEC A TESTS PASSED"),
        load_member("exec_b_main.ax.in", "qa_interp_exec_b.ax", "ALL INTERP EXEC B TESTS PASSED"),
    ]
    text = bc.assemble_merged_group(
        prelude_text,
        modules_text,
        members,
        timeout=900,
        extra_headers=["// Generated by tests/selfhost/interp/gen_interp_tests.py; do not edit directly."],
    )
    outs = [(os.path.join(HERE, "qa_interp_all.ax"), text)]
    return bc.write_or_check_bundles(outs, check_mode, root=ROOT)


if __name__ == "__main__":
    sys.exit(main())
