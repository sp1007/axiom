def main(argv):
    check = "--check" in argv
    files = all_files()
    stale = []
    (HERE / "prog").mkdir(exist_ok=True)
    for rel, text in sorted(files.items()):
        p = HERE / rel
        data = text.encode("utf-8")
        if check:
            if not p.is_file() or p.read_bytes() != data:
                stale.append(rel)
        else:
            p.write_bytes(data)
    if check:
        # a checked-in generated file that the generator no longer produces is stale too
        for p in HERE.rglob("*"):
            rel = p.relative_to(HERE).as_posix()
            if p.is_file() and p.suffix == ".ax" and rel not in files and "GENERATED by" in p.read_text(encoding="utf-8"):
                stale.append(rel + " (not generated)")
        if stale:
            sys.stderr.write("STALE: %s\nrun: python tests/conformance/p12/e12_1_integers/gen_conformance.py\n" % ", ".join(stale))
            return 1
        print("current (%d files)" % len(files))
        return 0
    print("wrote %d files" % len(files))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
