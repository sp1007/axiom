def result_helpers():
    out = []
    for (name, _, _) in TYPES:
        out.append("fn chk_%s(o: Option<%s>, some: bool, v: %s) -> bool {" % (name, name, name))
        out.append("    match o {")
        out.append("        Option.Some(x) => some && x == v,")
        out.append("        Option.None => !some,")
        out.append("    }")
        out.append("}")
        out.append("")
    return out


def gen_std_consistency():
    """checked_* / overflowing_* / wrapping_* / saturating_* agree with each other and with exact Python values."""
    lines = ["// test: helper",
             "// GENERATED by tests/conformance/p12/e12_1_integers/gen_conformance.py (T455). Do not edit by hand.",
             "// std: core/num.ax", ""]
    lines += result_helpers()
    fnames = []
    for (name, bits, signed) in TYPES:
        mn, mx = lo(bits, signed), hi(bits, signed)
        vals = boundary(bits, signed)
        for chunk_i in range(2):
            checks = []

            def v(x):
                return "(%s | z)" % lit(x, name)
            pairs = [(a, b) for a in vals for b in vals]
            half = (len(pairs) + 1) // 2
            for (a, b) in pairs[chunk_i * half:(chunk_i + 1) * half]:
                for opn, f in (("add", lambda x, y: x + y), ("sub", lambda x, y: x - y), ("mul", lambda x, y: x * y)):
                    r = f(a, b)
                    fits = mn <= r <= mx
                    some = "true" if fits else "false"
                    w = wrap(r, bits, signed)
                    checks.append("!chk_%s(%s.checked_%s(%s), %s, %s)" % (name, v(a), opn, v(b), some, lit(r if fits else 0, name)))
                    # overflowing_* returns (wrapped, flag); compare the pair through a local to avoid tuple names
                    checks.append("%s.overflowing_%s(%s).0 != %s" % (v(a), opn, v(b), lit(w, name)))
                    checks.append("%s.overflowing_%s(%s).1 != %s" % (v(a), opn, v(b), "false" if fits else "true"))
                    # cross-family identities
                    checks.append("%s.wrapping_%s(%s) != %s.overflowing_%s(%s).0" % (v(a), opn, v(b), v(a), opn, v(b)))
                    sat = max(mn, min(mx, r))
                    checks.append("%s.saturating_%s(%s) != %s" % (v(a), opn, v(b), lit(sat, name)))
                if b != 0 and not (signed and a == mn and b == -1):
                    checks.append("!chk_%s(%s.checked_div(%s), true, %s)" % (name, v(a), v(b), lit(trunc_div(a, b), name)))
                    checks.append("!chk_%s(%s.checked_rem(%s), true, %s)" % (name, v(a), v(b), lit(trunc_rem(a, b), name)))
                if b == 0:
                    checks.append("!chk_%s(%s.checked_div(%s), false, 0%s)" % (name, v(a), v(b), name))
                    checks.append("!chk_%s(%s.checked_rem(%s), false, 0%s)" % (name, v(a), v(b), name))
                if signed and a == mn and b == -1:
                    checks.append("!chk_%s(%s.checked_div(%s), false, 0%s)" % (name, v(a), v(b), name))
                    checks.append("!chk_%s(%s.checked_rem(%s), false, 0%s)" % (name, v(a), v(b), name))
                    checks.append("%s.wrapping_div(%s) != %s" % (v(a), v(b), lit(mn, name)))
                    checks.append("%s.saturating_div(%s) != %s" % (v(a), v(b), lit(mx, name)))
            fn = "std_%s_%d" % (name, chunk_i)
            fnames.append(fn)
            # split into functions of CHUNK checks
            sub = [checks[i:i + CHUNK] for i in range(0, len(checks), CHUNK)]
            for si, part in enumerate(sub):
                f = "%s_%d" % (fn, si)
                lines.append("fn %s(z: %s) -> i32 {" % (f, name))
                for k, cond in enumerate(part, 1):
                    lines.append("    if %s { return %d; }" % (cond, k))
                lines.append("    0")
                lines.append("}")
                lines.append("")
                fnames[-1] = fnames[-1]  # keep order
                fnames.append(f) if si or True else None
    # collect only the leaf functions (names ending with _<digit>_<digit>)
    leaf = [f for f in fnames if f.count("_") >= 3]
    # dedupe preserving order
    seen = set()
    leaf = [f for f in leaf if not (f in seen or seen.add(f))]
    lines.append("fn main() -> i32 {")
    for idx, f in enumerate(leaf):
        ty = f.split("_")[1]
        lines.append("    let r%d: i32 = %s(0%s);" % (idx, f, ty))
        lines.append("    if r%d != 0 { print(\"FAIL %s case \"); print_int(r%d as i64); print(\"\\n\"); return %d; }" % (idx, f, idx, (idx % 250) + 1))
    lines.append("    print(\"OK std_consistency\\n\");")
    lines.append("    0")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_std_endian():
    """to_/from_ {le,be,ne}_bytes: exact bytes, round trips and le/be mirror identity on all twelve types."""
    lines = ["// test: helper",
             "// GENERATED by tests/conformance/p12/e12_1_integers/gen_conformance.py (T455). Do not edit by hand.",
             "// std: core/num.ax", ""]
    leaf = []
    for (name, bits, signed) in TYPES:
        n = bits // 8
        m = (1 << bits) - 1
        vals = []
        for r in [0, 1, m, 1 << (bits - 1), (m >> 1), int("".join("%02x" % (i + 1) for i in range(n)), 16),
                  int("".join("%02x" % (0xF0 - i) for i in range(n)), 16)]:
            x = wrap(r, bits, signed)
            if x not in vals:
                vals.append(x)
        f = "endian_%s" % name
        leaf.append((f, name))
        lines.append("fn %s(z: %s) -> i32 {" % (f, name))
        k = 0
        for a in vals:
            ra = a & m
            le = list(ra.to_bytes(n, "little"))
            be = list(ra.to_bytes(n, "big"))
            va = "(%s | z)" % lit(a, name)
            # arrays are move-only in the current compiler (a by-value call argument moves it), so every use gets a
            # fresh array from the conversion under test
            def fresh(kind, idx=None):
                return "%s.to_%s_bytes()" % (va, kind)
            lines.append("    let le%d: [%d]u8 = %s.to_le_bytes();" % (k, n, va))
            lines.append("    let be%d: [%d]u8 = %s.to_be_bytes();" % (k, n, va))
            lines.append("    let ne%d: [%d]u8 = %s.to_ne_bytes();" % (k, n, va))
            for i in range(n):
                lines.append("    if le%d[%d] != %du8 { return %d; }" % (k, i, le[i], 1 + (k * n + i) % 200))
                lines.append("    if be%d[%d] != %du8 { return %d; }" % (k, i, be[i], 1 + (k * n + i) % 200))
                lines.append("    if ne%d[%d] != le%d[%d] { return %d; }" % (k, i, k, i, 1 + (k * n + i) % 200))
            lines.append("    if %s.from_le_bytes(%s) != %s { return %d; }" % (name, fresh("le"), lit(a, name), 201 + k))
            lines.append("    if %s.from_be_bytes(%s) != %s { return %d; }" % (name, fresh("be"), lit(a, name), 201 + k))
            lines.append("    if %s.from_ne_bytes(%s) != %s { return %d; }" % (name, fresh("ne"), lit(a, name), 201 + k))
            lines.append("    if %s.from_be_bytes(%s) != %s { return %d; }" % (name, fresh("le"), lit(wrap(int.from_bytes(bytes(le), "big"), bits, signed), name), 221 + k))
            lines.append("    if %s.from_le_bytes(%s) != %s { return %d; }" % (name, fresh("be"), lit(wrap(int.from_bytes(bytes(be), "little"), bits, signed), name), 221 + k))
            k += 1
        lines.append("    0")
        lines.append("}")
        lines.append("")
    lines.append("fn main() -> i32 {")
    for idx, (f, ty) in enumerate(leaf):
        lines.append("    let r%d: i32 = %s(0%s);" % (idx, f, ty))
        lines.append("    if r%d != 0 { print(\"FAIL %s case \"); print_int(r%d as i64); print(\"\\n\"); return %d; }" % (idx, f, idx, idx + 1))
    lines.append("    print(\"OK std_endian\\n\");")
    lines.append("    0")
    lines.append("}")
    return "\n".join(lines) + "\n"


