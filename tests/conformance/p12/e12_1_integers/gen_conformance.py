#!/usr/bin/env python3
"""T455 generator: E12.1 integer-model conformance suite (tests/conformance/p12/e12_1_integers/).

Every expected value is computed here with exact Python integers (never by the compiler or the library), so a
wrong compiler result cannot confirm itself.  The generated files are checked in; `--check` (run by
`generated_current.test`) fails when a checked-in file is stale.

    python gen_conformance.py            write the files
    python gen_conformance.py --check    verify the files are current (writes nothing)

Generated files (all twelve integer types i8 i16 i32 i64 i128 isize u8 u16 u32 u64 u128 usize):
  boundary_<ty>.ax   MIN/MAX/BITS constants, ordering, and `as` casts of the boundary values to every type
  arith_<ty>.ax      checked operators + - * / % at and next to the boundaries (results that fit; no panic)
  wrapsat_<ty>.ax    wrapping_* / saturating_* (built-in members) on boundary pairs, wrapping_neg
  bits_<ty>.ax       & | ^ ~, << >>, count_ones, leading/trailing_zeros, rotate_*, swap_bytes, reverse_bits
  panic_<op>_<ty>.ax every checked-overflow / zero-divisor / shift-range / MIN-by--1 trap, exit 101
  ui_*.ax            compile-time rejections (literal range, const overflow, const shift, mismatches)
  prog/std_*.ax      library programs run by std_*.test through tests/std/num/num_oracle.py in
                     run --interp, native -O0 and native -O1
"""

import os
