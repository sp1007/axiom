def panic_program(op, t):
    """Return (source, description) of one trap test; all operands arrive through parameters."""
    name, bits, signed = t
    mn, mx = lo(bits, signed), hi(bits, signed)
    body = {
        "add": ("a + b", lit(mx, name), lit(1, name), "MAX + 1"),
        "sub": ("a - b", lit(mn, name), lit(1, name), "MIN - 1"),
        "mul": ("a * b", lit(mx, name), lit(2, name), "MAX * 2"),
        "divzero": ("a / b", lit(mx, name), lit(0, name), "x / 0"),
        "remzero": ("a % b", lit(mx, name), lit(0, name), "x % 0"),
        "shl": ("a << 0u32 + b as u32", lit(1, name), lit(bits, name), "1 << BITS"),
        "shr": ("a >> 0u32 + b as u32", lit(mx, name), lit(bits, name), "MAX >> BITS"),
        "neg": ("-a", lit(mn, name), lit(0, name), "-MIN"),
        "divmin": ("a / b", lit(mn, name), lit(-1, name), "MIN / -1"),
        "remmin": ("a % b", lit(mn, name), lit(-1, name), "MIN % -1"),
    }[op]
    expr, a, b, what = body
    if op in ("shl", "shr"):
        # keep it simple: count is the u32 BITS, as an expression of a parameter
        expr = "a << c" if op == "shl" else "a >> c"
        src = [
            "// test: run", "// modes: interp native", "// exit: 101",
            "// stderr-contains: shift amount out of range",
            "// GENERATED by tests/conformance/p12/e12_1_integers/gen_conformance.py (T455). %s on %s must trap." % (what, name),
            "",
            "fn bad(a: %s, c: u32) -> %s {" % (name, name),
            "    return %s;" % expr,
            "}", "",
            "fn main() -> i32 {",
            "    let r: %s = bad(%s, %du32);" % (name, a, bits),
            "    if r == %s { return 7; }" % lit(1, name),
            "    print(\"UNREACHABLE: no trap\\n\");",
            "    return 0;",
            "}",
        ]
        return "\n".join(src) + "\n"
    msg = "division by zero" if op in ("divzero", "remzero") else "arithmetic overflow"
    src = [
        "// test: run", "// modes: interp native", "// exit: 101",
        "// stderr-contains: %s" % msg,
        "// GENERATED by tests/conformance/p12/e12_1_integers/gen_conformance.py (T455). %s on %s must trap." % (what, name),
        "",
    ]
    if op == "neg":
        src += ["fn bad(a: %s) -> %s {" % (name, name), "    return -a;", "}", "",
                "fn main() -> i32 {", "    let r: %s = bad(%s);" % (name, a)]
    else:
        src += ["fn bad(a: %s, b: %s) -> %s {" % (name, name, name), "    return %s;" % expr, "}", "",
                "fn main() -> i32 {", "    let r: %s = bad(%s, %s);" % (name, a, b)]
    src += ["    if r == %s { return 7; }" % lit(1, name),
            "    print(\"UNREACHABLE: no trap\\n\");",
            "    return 0;", "}"]
    return "\n".join(src) + "\n"


