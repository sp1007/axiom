def gen_boundary(t):
    name, bits, signed = t
    o = Out("boundary", hdr("boundary", name), None)
    mn, mx = lo(bits, signed), hi(bits, signed)
    z = "z"
    def v(x):
        return "(%s | %s)" % (lit(x, name), z)
    # associated constants and ordering
    o.check("%s.MIN | %s" % (name, z), lit(mn, name))
    o.check("%s.MAX | %s" % (name, z), lit(mx, name))
    o.check("%s.BITS" % name, "%du32" % bits)
    o.check("(%s.MAX - 1%s) | %s" % (name, name, z) if False else "%s.MAX.wrapping_sub(1%s) | %s" % (name, name, z), lit(mx - 1, name))
    vals = boundary(bits, signed)
    for a, b in zip(vals, vals[1:]):
        o.check("%s < %s" % (v(a), v(b)), "true")
        o.check("%s >= %s" % (v(a), v(b)), "false")
        o.check("%s != %s" % (v(a), v(b)), "true")
    for a in vals:
        o.check("%s == %s" % (v(a), lit(a, name)), "true")
        o.check("%s <= %s" % (v(a), v(a)), "true")
    # `as` casts of every boundary value to every type (truncation / sign extension / zero extension)
    for a in vals:
        for (dn, dbits, dsigned) in TYPES:
            o.check("%s as %s" % (v(a), dn), lit(wrap(a, dbits, dsigned), dn))
    return o.render("z: %s" % name, "0%s" % name, "OK boundary_%s" % name)


def gen_arith(t):
    name, bits, signed = t
    o = Out("arith", hdr("arith", name), None)
    mn, mx = lo(bits, signed), hi(bits, signed)
    vals = boundary(bits, signed)

    def v(x):
        return "(%s | z)" % lit(x, name)
    for a in vals:
        for b in vals:
            for op, f in (("+", lambda x, y: x + y), ("-", lambda x, y: x - y), ("*", lambda x, y: x * y)):
                r = f(a, b)
                if mn <= r <= mx:
                    o.check("%s %s %s" % (v(a), op, v(b)), lit(r, name))
            if b != 0 and not (signed and a == mn and b == -1):
                o.check("%s / %s" % (v(a), v(b)), lit(trunc_div(a, b), name))
                o.check("%s %% %s" % (v(a), v(b)), lit(trunc_rem(a, b), name))
    # signed truncation toward zero and the division identity on small operands
    if signed:
        for a, b in ((7, 2), (-7, 2), (7, -2), (-7, -2), (1, -3), (-1, 3)):
            o.check("%s / %s" % (v(a), v(b)), lit(trunc_div(a, b), name))
            o.check("%s %% %s" % (v(a), v(b)), lit(trunc_rem(a, b), name))
        for a in vals:
            if a != mn:
                o.check("-%s" % v(a), lit(-a, name))
        o.check("-(%s + 1%s)" % (v(mn), name), lit(mx, name))
    # MIN / 1, MAX / MAX, 0 / x and 0 % x stay exact
    o.check("%s / %s" % (v(mx), v(mx)), lit(1, name))
    o.check("%s %% %s" % (v(mx), v(mx)), lit(0, name))
    o.check("%s / %s" % (v(mn), v(1)), lit(mn, name))
    o.check("%s %% %s" % (v(mn), v(1)), lit(0, name))
    return o.render("z: %s" % name, "0%s" % name, "OK arith_%s" % name)


def gen_wrapsat(t):
    name, bits, signed = t
    o = Out("wrapsat", hdr("wrapsat", name), None)
    mn, mx = lo(bits, signed), hi(bits, signed)
    vals = boundary(bits, signed)

    def v(x):
        return "(%s | z)" % lit(x, name)
    for a in vals:
        for b in vals:
            for opn, f in (("add", lambda x, y: x + y), ("sub", lambda x, y: x - y), ("mul", lambda x, y: x * y)):
                r = f(a, b)
                o.check("%s.wrapping_%s(%s)" % (v(a), opn, v(b)), lit(wrap(r, bits, signed), name))
                o.check("%s.saturating_%s(%s)" % (v(a), opn, v(b)), lit(max(mn, min(mx, r)), name))
        o.check("%s.wrapping_neg()" % v(a), lit(wrap(-a, bits, signed), name))
    return o.render("z: %s" % name, "0%s" % name, "OK wrapsat_%s" % name)


def rotl(x, n, bits):
    n %= bits
    m = (1 << bits) - 1
    x &= m
    return ((x << n) | (x >> (bits - n))) & m if n else x


def gen_bits(t):
    name, bits, signed = t
    o = Out("bits", hdr("bits", name), None)
    m = (1 << bits) - 1
    mn, mx = lo(bits, signed), hi(bits, signed)
    pat55 = int(("01" * (bits // 2)), 2)
    patAA = int(("10" * (bits // 2)), 2)
    patF0 = int(("11110000" * (bits // 8)), 2)
    pat_seq = int("".join("%02x" % (i + 1) for i in range(bits // 8)), 16)
    raws = [0, 1, m, 1 << (bits - 1), pat55, patAA, patF0, pat_seq, (m >> 1), 6]
    vals = []
    for r in raws:
        x = wrap(r, bits, signed)
        if x not in vals:
            vals.append(x)

    def v(x):
        return "(%s | z)" % lit(x, name)
    for a in vals:
        ra = a & m
        o.check("%s.count_ones()" % v(a), "%du32" % bin(ra).count("1"))
        o.check("%s.leading_zeros()" % v(a), "%du32" % (bits - ra.bit_length()))
        o.check("%s.trailing_zeros()" % v(a), "%du32" % ((ra & -ra).bit_length() - 1 if ra else bits))
        for n in (0, 1, 3, bits - 1, bits, bits + 3):
            o.check("%s.rotate_left(%du32)" % (v(a), n), lit(wrap(rotl(ra, n, bits), bits, signed), name))
            o.check("%s.rotate_right(%du32)" % (v(a), n), lit(wrap(rotl(ra, bits - (n % bits), bits), bits, signed), name))
        swapped = int.from_bytes(ra.to_bytes(bits // 8, "little"), "big")
        o.check("%s.swap_bytes()" % v(a), lit(wrap(swapped, bits, signed), name))
        rev = int(format(ra, "0%db" % bits)[::-1], 2)
        o.check("%s.reverse_bits()" % v(a), lit(wrap(rev, bits, signed), name))
        o.check("~%s" % v(a), lit(wrap(~ra, bits, signed), name))
        for k in (0, 1, bits - 1):
            o.check("%s << %du32" % (v(a), k), lit(wrap(ra << k, bits, signed), name))
            sh = (a >> k) if signed else (ra >> k)   # Python >> on a negative int is arithmetic
            o.check("%s >> %du32" % (v(a), k), lit(sh, name))
    for a in vals:
        for b in vals[:6]:
            o.check("%s & %s" % (v(a), v(b)), lit(wrap((a & m) & (b & m), bits, signed), name))
            o.check("%s | %s" % (v(a), v(b)), lit(wrap((a & m) | (b & m), bits, signed), name))
            o.check("%s ^ %s" % (v(a), v(b)), lit(wrap((a & m) ^ (b & m), bits, signed), name))
    return o.render("z: %s" % name, "0%s" % name, "OK bits_%s" % name)


