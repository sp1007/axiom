HERE = Path(__file__).resolve().parent

TYPES = [
    ("i8", 8, True), ("i16", 16, True), ("i32", 32, True), ("i64", 64, True), ("i128", 128, True), ("isize", 64, True),
    ("u8", 8, False), ("u16", 16, False), ("u32", 32, False), ("u64", 64, False), ("u128", 128, False),
    ("usize", 64, False),
]
SIGNED = [t for t in TYPES if t[2]]
BY_NAME = {t[0]: t for t in TYPES}
CHUNK = 14


def lo(bits, signed):
    return -(1 << (bits - 1)) if signed else 0


def hi(bits, signed):
    return (1 << (bits - 1)) - 1 if signed else (1 << bits) - 1


def wrap(v, bits, signed):
    v &= (1 << bits) - 1
    if signed and v >= (1 << (bits - 1)):
        v -= 1 << bits
    return v


def lit(v, name):
    """Axiom literal of type `name`; negative values are parenthesised."""
    return "(-%d%s)" % (-v, name) if v < 0 else "%d%s" % (v, name)


def boundary(bits, signed):
    """The boundary values used by the arithmetic tables, ascending and distinct."""
    mn, mx = lo(bits, signed), hi(bits, signed)
    vals = [mn, mn + 1, -1, 0, 1, mx - 1, mx] if signed else [0, 1, 2, mx // 2, mx // 2 + 1, mx - 1, mx]
    return sorted(set(vals))


def trunc_div(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def trunc_rem(a, b):
    return a - trunc_div(a, b) * b


class Out:
    """Accumulates (condition-expression, text) checks and renders the chunked program."""

    def __init__(self, name, header, params_for):
        self.name = name
        self.header = header
        self.params_for = params_for
        self.checks = []

    def check(self, expr, expected):
        self.checks.append("(%s) != (%s)" % (expr, expected))

    def render(self, z_params, z_args, ok_line):
        lines = []
        lines.extend(self.header)
        nchunks = (len(self.checks) + CHUNK - 1) // CHUNK
        for c in range(nchunks):
            part = self.checks[c * CHUNK:(c + 1) * CHUNK]
            lines.append("")
            lines.append("fn chunk_%d(%s) -> i32 {" % (c, z_params))
            for k, cond in enumerate(part, 1):
                lines.append("    if %s { return %d; }" % (cond, k))
            lines.append("    0")
            lines.append("}")
        lines.append("")
        lines.append("fn main() -> i32 {")
        for c in range(nchunks):
            lines.append("    let r%d: i32 = chunk_%d(%s);" % (c, c, z_args))
            lines.append("    if r%d != 0 { print(\"FAIL chunk %d case \"); print_int(r%d as i64); print(\"\\n\"); return %d; }" % (c, c, c, c + 1))
        lines.append("    print(\"%s\\n\");" % ok_line)
        lines.append("    0")
        lines.append("}")
        return "\n".join(lines) + "\n"


Z_PARAMS = "z: %s"


def hdr(kind, tyname, extra=None):
    h = ["// test: run", "// modes: interp native"]
    h.append("// stdout: OK %s_%s\\n" % (kind, tyname))
    h.append("// GENERATED by tests/conformance/p12/e12_1_integers/gen_conformance.py (T455). Do not edit by hand.")
    if extra:
        h.extend(extra)
    return h


