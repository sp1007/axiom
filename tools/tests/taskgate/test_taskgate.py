    def test_tool_selftest_failing_at_head_is_known_not_new(self):
        failing = ("import sys\nprint('FAIL: test_old (test_x.C.test_old)')\n"
                   "print('SELFTEST 2 tests, 1 failures')\nsys.exit(1)\n")
        self.write("tools/tests/axtest/run_selftests.py", failing)
        self.commit("pre-existing failure at HEAD")
        self.write("tools/axtest_extra.py", "# change\n")
        self.assertEqual(self.gate(), 0, self.out)
        t = self.json["tools"][0]
        self.assertEqual(t["state"], "KNOWN")
        self.assertEqual(t["known"], ["tools/tests/axtest::test_x.C.test_old"])
        self.assertIn("known tool self-test failure (fails at HEAD too / baseline): "
                      "`tools/tests/axtest::test_x.C.test_old`", self.out)
        # a further failure that HEAD does not have is new
        self.write("tools/tests/axtest/run_selftests.py", failing.replace(
            "print('SELFTEST", "print('ERROR: test_new (test_x.C.test_new)')\nprint('SELFTEST"))
        self.assertEqual(self.gate(), 1)
        self.assertEqual(self.json["tools"][0]["new"], ["tools/tests/axtest::test_x.C.test_new"])
        self.assertIn("NEW tool self-test failure: `tools/tests/axtest::test_x.C.test_new`", self.out)
        # ... unless the baseline lists it
        self.write("_workspaces/baseline-failures.txt",
                   "tools/tests/axtest::test_x.C.test_new  undiagnosed:x  T999\n")
        self.assertEqual(self.gate(), 0, self.out)

