class Fixture(unittest.TestCase):
    root_name = "repo with space"

    def setUp(self):
        self.base = Path(tempfile.mkdtemp(prefix="taskgate-self-"))
        self.root = self.base / self.root_name
        for rel, text in FIXTURE.items():
            self.write(rel, text)
        for n in ("axtest.py", "axtest_cache.py", "axtest_affected.py", "taskgate.py"):
            shutil.copy2(TOOLS / n, self.root / "tools" / n)
        self.git("init", "-q")
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "base")
        self.base_commit = self.git("rev-parse", "HEAD")
        self.cache = self.base / "cache"

    def tearDown(self):
        shutil.rmtree(self.base, ignore_errors=True)

    def write(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8") if isinstance(text, str) else text)
        return p

    def git(self, *args):
        env = dict(os.environ)
        env.update(GIT_ENV)
        r = subprocess.run(["git", *args], cwd=str(self.root), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                           env=env)
        if r.returncode != 0:
            raise RuntimeError("git %s: %s" % (args, r.stderr.decode("utf-8", "replace")))
        return r.stdout.decode("utf-8").strip()

    def commit(self, msg="change"):
        self.git("add", "-A")
        self.git("commit", "-q", "-m", msg)
        return "%s..HEAD" % self.base_commit

    def derive(self, *args):
        tests = axtest.discover(self.root / "tests")
        return axtest_affected.derive(self.root, list(args), tests, self.cache)

    def tool(self, name, *args, env=None):
        full = dict(os.environ)
        for k in list(full):
            if k.startswith("STUB_"):
                full.pop(k)
        full.update(env or {})
        cmd = [sys.executable, str(self.root / "tools" / name), *args]
        p = subprocess.run(cmd, cwd=str(self.root), stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=full)
        self.out = p.stdout.decode("utf-8", "replace")
        self.err = p.stderr.decode("utf-8", "replace")
        return p.returncode


